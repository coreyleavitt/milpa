"""nim.cfg emission from a resolved dep graph.

Generates a `nim.cfg` file at the consuming project's root with one
``--path:`` line per resolved dep. The Nim compiler reads this file
automatically when invoked from the project directory and adds the
listed paths to its import search — no nimble involvement needed.

Owns:
  - format_nimcfg(graph, *, deps_dir, self_src_dir) -> str
  - format_workspace_nimcfgs(workspace, graph) -> dict[str, str]  [S9d]

Spec references: lockfile-schema.md §7.1–7.4 (normative); §7.5 deferred
(feature-flag -d: defines, tracked at #23); §7.6 (workspace per-member
emission).
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path
from typing import TYPE_CHECKING

from milpa.lockfile import MemberProvenanceRecord, ResolvedDep, ResolvedGraph

if TYPE_CHECKING:
    from milpa.workspace import LoadedMember, LoadedWorkspace

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

#: The normative three-line header (§7.1). Stored without its trailing newline;
#: the emission logic joins lines and adds newlines.
_HEADER_LINES = (
    "# generated by milpa; do not edit",
    "# manifest: milpa.kdl",
    "# lockfile: milpa.lock",
)


# ---------------------------------------------------------------------------
# format_nimcfg — normative single-package emitter (§7.1–7.4)
# ---------------------------------------------------------------------------


def format_nimcfg(
    graph: ResolvedGraph,
    *,
    deps_dir: Path = Path("_deps"),
    self_src_dir: str = "",
) -> str:
    """Render *graph* into ``nim.cfg`` text (lockfile-schema.md §7.1–7.4).

    Emission order (§7.4):

    1. File-level header comment (§7.1) — always present, even for an empty
       graph.
    2. Self src-dir path — ``--path:"<self_src_dir>"`` — emitted first (before
       dep paths) when *self_src_dir* is non-empty, so self-modules shadow
       same-named dep import paths.
    3. Dep ``--path:`` lines — one per dep, sorted lexicographically by dep name
       (resolver-semantics.md §4.4 — the single canonical ordering rule; a
       toposort's sibling tie-break is not reproducible across implementations).
    4. Feature-flag ``-d:`` defines (§7.5) — **DEFERRED** (#23). No active flag
       emit here. ``ResolvedDep`` carries ``active_flags`` but no corpus fixture
       exercises it and the Rust reference defers it too.

    When groups (2)+(3) are both empty the file contains only the header
    (§7.4: "Groups (1) and (2) are omitted when empty"). The file ends with a
    single trailing ``\\n`` — not a blank line (§7.4 NOTE).

    All paths use POSIX separators regardless of host OS (§7.2).
    """
    path_lines: list[str] = []

    if self_src_dir:
        path_lines.append(f'--path:"{self_src_dir}"')

    # Lexicographic by dep name — spec's single canonical ordering rule.
    ordered = sorted(graph.deps, key=lambda d: d.name)
    for dep in ordered:
        path_lines.append(f'--path:"{_path_for(dep, deps_dir)}"')

    # §7.5 feature-flag defines — DEFERRED (#23). When implemented, a
    # separate block separated by a blank line will be appended here for
    # each dep.active_flags entry.

    if path_lines:
        # Header + blank line separator + path block + trailing newline.
        return "\n".join([*_HEADER_LINES, "", *path_lines]) + "\n"
    else:
        # No deps, no self src-dir: header only, trailing newline (§7.4).
        return "\n".join(_HEADER_LINES) + "\n"


def _path_for(dep: ResolvedDep, deps_dir: Path) -> str:
    """Compute ``<deps_dir>/<name>[/<src_dir>]`` in POSIX form (§7.3).

    *deps_dir* may be a relative Path like ``Path("_deps")``; ``as_posix()``
    yields ``"_deps"`` which is correct. An absolute Path gives ``"/abs/path"``.
    """
    base = deps_dir.as_posix() + "/" + dep.name
    if dep.src_dir:
        base += "/" + dep.src_dir
    return base


# ---------------------------------------------------------------------------
# format_workspace_nimcfgs — per-member nim.cfg emission (S9d / §7.6)
# ---------------------------------------------------------------------------


def format_workspace_nimcfgs(
    workspace: LoadedWorkspace,
    graph: ResolvedGraph,
) -> dict[str, str]:
    """Per-member ``nim.cfg`` emitter for workspace projects (§7.6).

    Returns a ``dict`` mapping each member's as-declared workspace-relative
    ``rel_path`` to its ``nim.cfg`` text.

    Per-member layout (§7.6):
    - Each member receives only the deps in its transitive closure.
    - Dep paths are relative from the member's directory:
        - External deps (git/tarball/named): ``<root_to_member>/_deps/<name>[/src]``
          expressed as relative from the member dir.
        - Member deps: relative from the member dir to the other member's dir
          (plus any src_dir suffix).
    - Deps are sorted lexicographically by dep name (same as single-package).
    - No self src-dir emit in workspace members (each member is a library
      peer, not a "consuming project" from the workspace root's perspective).

    ``workspace`` is a ``LoadedWorkspace``; typed as ``object`` to avoid
    circular imports (nimcfg.py must not import workspace.py).
    """
    # Build lookup structures from the workspace and graph.
    # member.rel_path → member.abs_dir (LoadedMember fields accessed by name)
    member_by_name: dict[str, LoadedMember] = {}
    for m in workspace.members:
        member_by_name[m.manifest.name] = m

    workspace_root: Path = workspace.root_dir

    # Build graph lookups
    dep_by_name: dict[str, ResolvedDep] = {d.name: d for d in graph.deps}

    out: dict[str, str] = {}

    for member in workspace.members:
        member_name: str = member.manifest.name
        member_abs_dir: Path = member.abs_dir
        member_rel_path: str = member.rel_path

        # Compute transitive closure for this member (excluding member itself).
        closure = _member_dep_closure(graph, dep_by_name, member_name)

        # Sort lexicographically by dep name (§4.4 / §7.4).
        closure_sorted = sorted(closure, key=lambda d: d.name)

        path_lines: list[str] = []
        for dep in closure_sorted:
            target = _dep_target(
                dep, workspace_root, member_by_name
            )
            rel = _relpath_posix(target, member_abs_dir)
            path_lines.append(f'--path:"{rel}"')

        if path_lines:
            text = "\n".join([*_HEADER_LINES, "", *path_lines]) + "\n"
        else:
            text = "\n".join(_HEADER_LINES) + "\n"

        out[member_rel_path] = text

    return out


def _dep_target(
    dep: ResolvedDep,
    workspace_root: Path,
    member_by_name: Mapping[str, LoadedMember],
) -> Path:
    """Compute the absolute source path for ``dep``.

    For workspace members: ``member.abs_dir[/src_dir]``.
    For external deps:     ``workspace_root/_deps/<name>[/src_dir]``.
    """
    if _is_member_dep(dep) and dep.name in member_by_name:
        base: Path = member_by_name[dep.name].abs_dir
    else:
        base = workspace_root / "_deps" / dep.name

    if dep.src_dir:
        return base / dep.src_dir
    return base


def _is_member_dep(dep: ResolvedDep) -> bool:
    """True when the dep has a MemberProvenanceRecord (workspace member)."""
    return isinstance(dep.provenance, MemberProvenanceRecord)


def _member_dep_closure(
    graph: ResolvedGraph,
    dep_by_name: dict[str, ResolvedDep],
    member_name: str,
) -> list[ResolvedDep]:
    """Return the transitive closure reachable from ``member_name``.

    Excludes the member itself. Mirrors Rust ``member_dep_closure``.
    """
    visited: set[str] = set()
    result: list[ResolvedDep] = []

    def _visit(name: str) -> None:
        if name in visited:
            return
        dep = dep_by_name.get(name)
        if dep is None:
            return
        visited.add(name)
        for req in dep.requires:
            _visit(req)
        result.append(dep)

    member_dep = dep_by_name.get(member_name)
    if member_dep is not None:
        for req in member_dep.requires:
            _visit(req)

    return result


def _relpath_posix(target: Path, base: Path) -> str:
    """Return a POSIX relative path from ``base`` directory to ``target``.

    Equivalent to ``os.path.relpath(target, start=base)`` but in POSIX form.
    Both paths should be absolute.
    """
    target_parts = target.parts
    base_parts = base.parts

    # Find the common prefix length.
    common = 0
    for t, b in zip(target_parts, base_parts, strict=False):
        if t == b:
            common += 1
        else:
            break

    up = len(base_parts) - common
    down = target_parts[common:]

    parts: list[str] = [".."] * up + list(down)
    if not parts:
        return "."
    return "/".join(parts)
