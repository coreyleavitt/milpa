def parse_lockfile(text: str) -> Lockfile:
    """Parse KDL 2.0 lockfile text into a ``Lockfile`` value.

    Raises ``MilpaError`` with LOCK-* slugs on any parse error.
    Strict parser (S3): both ``version`` and ``strategy`` are required.
    """
    doc = parse_kdl(text, context="lockfile")

    deps: list[LockedDep] = []
    strategy: str | None = None
    schema_version: int | None = None
    exclude_newer: datetime | None = None

    for node in nodes(doc):
        name = node_name(node)
        if name == "version":
            schema_version = _parse_top_version(node)
        elif name == "strategy":
            strategy = _parse_top_strategy(node)
        elif name == "exclude_newer":
            exclude_newer = _parse_top_exclude_newer(node)
        elif name == "dep":
            deps.append(_parse_dep(node))
        # Any other top-level node is silently ignored for forward compat

    if schema_version is None:
        raise MilpaError(
            LOCK_VERSION_MISSING,
            "lockfile missing required 'version' node",
        )
    if schema_version != LOCKFILE_SCHEMA_VERSION:
        raise MilpaError(
            LOCK_VERSION_UNSUPPORTED,
            f"unsupported lockfile schema version {schema_version} "
            f"(this milpa understands version {LOCKFILE_SCHEMA_VERSION})",
            got=schema_version,
            supported=LOCKFILE_SCHEMA_VERSION,
        )
    if strategy is None:
        raise MilpaError(
            LOCK_STRATEGY_MISSING,
            "lockfile missing required 'strategy' node; regenerate via 'milpa fetch'",
        )

    return Lockfile(
        deps=tuple(deps),
        strategy=strategy,
        version=schema_version,
        exclude_newer=exclude_newer,
    )


def _parse_top_version(node: KdlNode) -> int:
    """Parse the top-level ``version`` node → schema version integer."""
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_FIELD_ARITY,
            f"'version' node takes exactly one argument, got {len(args)}",
        )
    val = args[0]
    as_int = value_as_int(val)
    if as_int is None:
        raise MilpaError(
            LOCK_FIELD_TYPE,
            f"'version' must be an integer, got {val!r}",
            got=val,
        )
    return as_int


def _parse_top_strategy(node: KdlNode) -> str:
    """Parse the top-level ``strategy`` node → strategy name string.

    S3 strict: the strategy node must have exactly one string argument.
    A present-but-malformed node (e.g. ``strategy 42`` — non-string arg,
    or wrong arity) raises ``LOCK-STRATEGY-MISSING``, matching Rust's
    ``parse_lockfile`` which leaves ``strategy`` unset when the arg is not a
    string and then raises ``LOCK-STRATEGY-MISSING`` at the ``ok_or_else``
    site.
    """
    args = node_args(node)
    if len(args) == 1:
        s = value_as_str(args[0])
        if s is not None:
            return s
    raise MilpaError(
        LOCK_STRATEGY_MISSING,
        "lockfile 'strategy' node has no valid string argument; "
        "regenerate via 'milpa fetch'",
    )


def _parse_top_exclude_newer(node: KdlNode) -> datetime:
    """Parse the OPTIONAL top-level ``exclude_newer`` node → a ``datetime``.

    D5 (resolution-semantics RFC §3 Axis D / §5). Unlike ``strategy``
    (required), this node is optional — absent entirely when no bound is in
    effect. A PRESENT-but-malformed node (wrong arity, non-string arg, or an
    unparseable ISO 8601 timestamp) is still a hard parse error — mirrors
    ``_parse_top_version``'s arity/type-error convention (``LOCK_FIELD_ARITY``
    / ``LOCK_FIELD_TYPE``), not a new dedicated slug.
    """
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_FIELD_ARITY,
            f"'exclude_newer' node takes exactly one argument, got {len(args)}",
        )
    val = args[0]
    s = value_as_str(val)
    if s is None:
        raise MilpaError(
            LOCK_FIELD_TYPE,
            f"'exclude_newer' must be a string, got {val!r}",
            got=val,
        )
    parsed = _parse_timestamp(s)
    if parsed is None:
        raise MilpaError(
            LOCK_FIELD_TYPE,
            f"'exclude_newer' value {s!r} is not a valid ISO 8601 timestamp",
            got=s,
        )
    return parsed


def _parse_dep(node: KdlNode) -> LockedDep:
    """Parse a ``dep`` block into a ``LockedDep``."""
    dep_name = _require_dep_name(node)

    identity: str | None = None
    version: str = "0.0.0"
    src_dir: str = ""
    requires: tuple[str, ...] = ()
    active_flags: tuple[str, ...] = ()
    provenances: list[ProvenanceRecord] = []
    dep_decl: str | None = None  # S6: additive dep_decl pin (§3.7)
    cond_requires: list[CondRequire] = []  # S4: additive cond-require annotations
    aliases: tuple[str, ...] = ()  # Phase B: alternate names for deduped deps
    namespace: str | None = None  # C1: qualified dep namespace (§3.9)
    attestation: LockAttestation | None = None  # per-entry attestation claim (§3.9)
    declared_version_source: str | None = None  # A5: sibling source for `version`
    source_id: SourceId | None = None  # S5: structured on-disk source-id (§4.1/§7)

    for child in node_children(node):
        cname = node_name(child)
        if cname == "namespace":
            # C1: parse the optional namespace child node (§3.9).
            # Form: ``namespace "<ns>"`` — exactly one string arg.
            # Security: validate charset at the lockfile parse boundary.
            # A poisoned milpa.lock with namespace "ns/../../x" would escape
            # _deps/ via dep_dir_name → "@ns/../../x/<name>".  Reuse the
            # dep-name charset predicate (valid_dep_name / LOCK-DEP-NAME-INVALID)
            # — same predicate as dep names and aliases.
            # Empty namespace → skip/ignore (parity with Rust !is_empty() guard).
            ns_args = node_args(child)
            if len(ns_args) == 1:
                ns_val = value_as_str(ns_args[0])
                if ns_val is not None and ns_val:  # skip empty (Rust parity)
                    if not valid_dep_name(ns_val):
                        raise MilpaError(
                            LOCK_DEP_NAME_INVALID,
                            f"dep {dep_name!r}: lockfile 'namespace' value {ns_val!r} "
                            f"contains characters outside [A-Za-z0-9_-] — "
                            "rejected to prevent path traversal via a poisoned milpa.lock",
                            name=ns_val,
                        )
                    namespace = ns_val
            # Malformed namespace child (wrong arity / non-string) is silently
            # skipped for forward-compat (same spirit as "skip unknown child nodes").
        elif cname == "identity":
            identity = _parse_dep_identity(child, dep_name)
        elif cname == "version":
            version = _parse_dep_scalar_str(child, dep_name, "version")
        elif cname == "declared_version_source":
            # A5: forward-compat lenient parse (mirrors the attestation
            # ``kind`` collapse convention, lockfile-schema.md §3.9) — an
            # unrecognized value or malformed arity silently collapses to
            # None rather than raising; no new error slug is warranted for
            # a purely additive/diagnostic field.
            _dvs_args = node_args(child)
            if len(_dvs_args) == 1:
                _dvs_val = value_as_str(_dvs_args[0])
                if _dvs_val is not None:
                    try:
                        declared_version_source = str(VersionSource(_dvs_val))
                    except ValueError:
                        declared_version_source = None
        elif cname == "src_dir":
            src_dir = _parse_dep_scalar_str(child, dep_name, "src_dir")
            # Security: validate src_dir at the lockfile parse boundary.
            # A poisoned milpa.lock with unsafe chars in src_dir would flow to
            # nim.cfg --path: on frozen reconstruction.  Reuse the SSOT predicate
            # (contains_unsafe_char from manifest.py); mirrors Rust lockfile.rs.
            if src_dir and contains_unsafe_char(src_dir):
                raise MilpaError(
                    LOCK_SRC_DIR_UNSAFE,
                    f"dep {dep_name!r}: lockfile 'src_dir' value contains a "
                    f"control character or line separator — rejected to prevent "
                    f"nim.cfg injection via a poisoned milpa.lock",
                    dep=dep_name,
                )
        elif cname == "requires":
            requires = _parse_dep_requires(child)
        elif cname == "aliases":
            aliases = _parse_dep_aliases(child)
        elif cname == "active_flags":
            active_flags = _parse_dep_active_flags(child)
        elif cname == "attestation":
            attestation = _parse_lock_attestation(child, dep_name)
        elif cname == "source":
            # RFC origin-as-identity.md §4.1/§7 (S5): structured on-disk
            # source-id — field-by-field into the frozen SourceId struct,
            # never a flat-string parse.
            source_id = _parse_source_block(child, dep_name)
        elif cname == "provenance":
            provenances.append(_parse_provenance_block(child, dep_name))
        elif cname == "dep_decl":
            # S6: forward-compat parse — silently ignored when absent or malformed.
            args = node_args(child)
            if len(args) == 1:
                dep_decl = value_as_str(args[0])
        elif cname == "cond-require":
            # S4: parse additive cond-require annotation (RFC §3.4).
            cr = _parse_cond_require(child)
            if cr is not None:
                cond_requires.append(cr)
        # other unknown child nodes are silently skipped (forward compat)

    return LockedDep(
        name=dep_name,
        identity=identity,
        version=version,
        src_dir=src_dir,
        requires=requires,
        provenances=tuple(provenances),
        active_flags=active_flags,
        dep_decl=dep_decl,
        cond_requires=tuple(cond_requires),
        aliases=aliases,
        namespace=namespace,
        attestation=attestation,
        declared_version_source=declared_version_source,
        source_id=source_id,
    )


def _require_dep_name(node: KdlNode) -> str:
    """Extract the dep name from the positional arg of a ``dep`` node.

    Validates the name against the dep-name charset [A-Za-z0-9_-]+ (SSOT:
    ``manifest.valid_dep_name``).  A poisoned
    lockfile with a name like ``../evil`` (containing ``/``) would otherwise
    flow to ``nim.cfg --path:`` and ``deps_dir / name``.  We use the charset
    predicate here, NOT ``contains_unsafe_char``, because ``/`` and ``.`` are
    not control characters.
    """
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_DEP_NAME_ARITY,
            f"dep node requires exactly one string argument (the name), "
            f"got {len(args)} args",
        )
    name = value_as_str(args[0])
    if name is None:
        raise MilpaError(
            LOCK_DEP_NAME_ARITY,
            f"dep node name argument must be a string, got {args[0]!r}",
        )
    # R8-S1 security fix: validate dep name charset at the lockfile parse
    # boundary.  Mirrors the manifest parse boundary check (MAN-DEP-NAME-INVALID).
    if not valid_dep_name(name):
        raise MilpaError(
            LOCK_DEP_NAME_INVALID,
            f"dep name {name!r} contains characters outside [A-Za-z0-9_-] — "
            "rejected to prevent path traversal and nim.cfg injection via a "
            "poisoned milpa.lock",
            name=name,
        )
    return name


def _parse_dep_identity(node: KdlNode, dep_name: str) -> str:
    """Parse the ``identity`` child of a dep block."""
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_DEP_FIELD_ARITY,
            f"dep {dep_name!r}: 'identity' must have exactly one string value",
            dep=dep_name,
        )
    val = args[0]
    # Validate multihash format (lockfile-schema.md §3.1)
    return _parse_dep_identity_str(val, dep_name)


def _parse_dep_scalar_str(node: KdlNode, dep_name: str, field: str) -> str:
    """Parse a dep child node that takes exactly one string arg."""
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_DEP_FIELD_ARITY,
            f"dep {dep_name!r}: {field!r} must have exactly one string value, "
            f"got {len(args)} args",
            dep=dep_name,
            field=field,
        )
    s = value_as_str(args[0])
    if s is None:
        raise MilpaError(
            LOCK_DEP_FIELD_ARITY,
            f"dep {dep_name!r}: {field!r} value must be a string, got {args[0]!r}",
            dep=dep_name,
            field=field,
        )
    return s


def _parse_dep_requires(node: KdlNode) -> tuple[str, ...]:
    """Parse the ``requires`` child node — zero or more string args."""
    return tuple(s for a in node_args(node) if (s := value_as_str(a)) is not None)


def _parse_dep_active_flags(node: KdlNode) -> tuple[str, ...]:
    """Parse the ``active_flags`` child node — zero or more string args."""
    return tuple(s for a in node_args(node) if (s := value_as_str(a)) is not None)


def _parse_dep_aliases(node: KdlNode) -> tuple[str, ...]:
    """Parse the ``aliases`` child node — zero or more string args.

    Returned tuple is lexicographically sorted (canonical form per §3.8).

    Each alias is validated against the dep-name charset [A-Za-z0-9_-]+
    (same SSOT predicate as dep names — R8-S1 security fix).  Aliases reach
    the same filesystem and nim.cfg sinks as the primary dep name.
    """
    aliases = []
    for a in node_args(node):
        s = value_as_str(a)
        if s is None:
            continue
        if not valid_dep_name(s):
            raise MilpaError(
                LOCK_DEP_NAME_INVALID,
                f"dep alias {s!r} contains characters outside [A-Za-z0-9_-] — "
                "rejected to prevent path traversal and nim.cfg injection via a "
                "poisoned milpa.lock",
                name=s,
            )
        aliases.append(s)
    return tuple(sorted(aliases))


def _parse_lock_attestation(node: KdlNode, dep_name: str) -> LockAttestation | None:
    """Parse the ``attestation { kind; signer; rekor { … } }`` block (§3.9).

    Malformed input (unrecognized ``kind``, or ``"author-signed"`` with no
    ``signer``) collapses to ``None`` with a diagnostic naming *dep_name* —
    the same conservative-collapse posture registry-protocol.md §3.2 defines
    for index parsing, applied here to a lockfile being read
    (lockfile-schema.md §3.9 NORMATIVE).
    """
    kind_label: str | None = None
    signer: str | None = None
    rekor: RekorRef | None = None
    bundle_pin: str | None = None
    namespace: str = ""

    for child in node_children(node):
        cname = node_name(child)
        if cname == "kind":
            args = node_args(child)
            kind_label = value_as_str(args[0]) if args else None
        elif cname == "signer":
            args = node_args(child)
            signer = value_as_str(args[0]) if args else None
        elif cname == "rekor":
            rekor = _parse_lock_rekor_block(child)
        elif cname == "bundle":
            # P3a: delivery-integrity pin (lockfile-schema.md §3.9 P3a addition).
            bundle_pin = node_prop_str(child, "sha256")
        elif cname == "namespace":
            # P3a: the entry's REAL index namespace — absent on P2-vintage
            # lockfiles (forward-compat: defaults to "" — the same value an
            # unqualified index entry would carry).
            args = node_args(child)
            namespace = (value_as_str(args[0]) if args else None) or ""

    if kind_label == "author-signed":
        if not signer:
            warnings.warn(
                f"dep {dep_name!r}: lockfile attestation block collapsed to "
                f"absent — \"author-signed\" with no signer (lockfile-schema §3.9)",
                stacklevel=2,
            )
            return None
        return LockAttestation(
            kind=AuthorSigned(signer=signer), rekor=rekor, bundle_pin=bundle_pin, namespace=namespace
        )

    if kind_label == "milpa-vendored":
        return LockAttestation(
            kind=MilpaVendored(), rekor=rekor, bundle_pin=bundle_pin, namespace=namespace
        )

    warnings.warn(
        f"dep {dep_name!r}: lockfile attestation block collapsed to absent — "
        f"unrecognized kind {kind_label!r} (lockfile-schema §3.9)",
        stacklevel=2,
    )
    return None


def _parse_lock_rekor_block(node: KdlNode) -> RekorRef:
    """Parse the nested ``rekor { uuid; log_index; integrated_time }`` block."""

    def _scalar(name: str) -> str:
        for child in node_children(node):
            if node_name(child) == name:
                args = node_args(child)
                if args:
                    return value_as_str(args[0]) or ""
        return ""

    return RekorRef(
        uuid=_scalar("uuid"),
        log_index=_scalar("log_index"),
        integrated_time=_scalar("integrated_time"),
    )


def _parse_cond_require(node: KdlNode) -> "CondRequire | None":
    """Parse a ``cond-require`` child node (RFC §3.4 / S4).

    Inline form (single predicate as props):
        ``cond-require "name" platform="linux"``
        ``cond-require "name" platform=(not)"linux"``

    Block form (≥2 predicates as ``when`` children):
        ``cond-require "name" { when platform="macosx" when platform=(not)"linux" }``

    Returns ``None`` (lenient/forward-compat) if the node is malformed
    (missing name arg, unknown shape).  Unknown extra fields are skipped.
    """
    # arg0 = require name
    args = node_args(node)
    if not args:
        return None
    name = value_as_str(args[0])
    if name is None:
        return None

    predicates: list[Predicate] = []

    children = node_children(node)
    if children:
        # Block form: each child MUST be a "when" node with exactly one prop.
        for child in children:
            if node_name(child) != "when":
                continue  # skip unknown child nodes (forward compat)
            props = node_props(child)
            for key in props:
                # M1: whitelist-validate the predicate name from untrusted input.
                # Keys outside the known vocabulary are silently dropped
                # (forward-compat lenient — same as "skip unknown nodes").
                if key not in _KNOWN_PREDICATE_NAMES:
                    continue
                val = node_prop_str(child, key)
                if val is None:
                    continue
                tag = node_prop_tag(child, key)
                predicates.append(
                    Predicate(name=key, values=(val,), negated=(tag == "not"))
                )
    else:
        # Inline form: each prop is one predicate.
        props = node_props(node)
        for key in props:
            # M1: whitelist-validate the predicate name from untrusted input.
            if key not in _KNOWN_PREDICATE_NAMES:
                continue
            val = node_prop_str(node, key)
            if val is None:
                continue
            tag = node_prop_tag(node, key)
            predicates.append(
                Predicate(name=key, values=(val,), negated=(tag == "not"))
            )

    if not predicates:
        return None
    return CondRequire(name=name, predicates=tuple(predicates))


# ---------------------------------------------------------------------------
# source { … } — structured on-disk SourceId (RFC origin-as-identity.md
# §4.1/§7, S5). Field-by-field into the frozen SourceId struct — NO
# flat-string parse. A `/`-bearing namespace stores losslessly as an
# ordinary KDL string value.
# ---------------------------------------------------------------------------

_SOURCE_KIND_LABELS = ("git", "oci", "tarball", "local", "registry", "member")


def _parse_source_block(node: KdlNode, dep_name: str) -> SourceId:
    """Parse a ``source { kind "…"; … }`` block into a typed ``SourceId``.

    Structural (arity/missing-field) errors raise ``LOCK-SRC-*``; the parsed
    RAW struct is then passed through ``normalize_source`` (SourceId's own
    sole validation boundary — module docstring), which raises
    ``SRC-ID-MALFORMED`` on a malformed subpath / namespace / registry
    component so a poisoned lockfile cannot smuggle a `..`-traversal subpath
    or a control-char namespace segment past the parse boundary.
    """
    fields: dict[str, str] = {}
    for child in node_children(node):
        cname = node_name(child)
        child_args = node_args(child)
        if len(child_args) != 1:
            raise MilpaError(
                LOCK_SRC_FIELD_ARITY,
                f"dep {dep_name!r}: source field {cname!r} must have exactly "
                f"one value, got {len(child_args)}",
                dep=dep_name,
                field=cname,
            )
        raw = child_args[0]
        s = value_as_str(raw)
        if s is None:
            raise MilpaError(
                LOCK_SRC_FIELD_ARITY,
                f"dep {dep_name!r}: source field {cname!r} must be a string, "
                f"got {raw!r}",
                dep=dep_name,
                field=cname,
            )
        fields[cname] = s

    kind = fields.get("kind")
    if kind is None:
        raise MilpaError(
            LOCK_SRC_KIND_MISSING,
            f"dep {dep_name!r}: source block missing 'kind' discriminator",
            dep=dep_name,
        )

    def _req(key: str) -> str:
        val = fields.get(key)
        if val is None:
            raise MilpaError(
                LOCK_SRC_FIELD_MISSING,
                f"dep {dep_name!r}: source block (kind={kind!r}) missing "
                f"required field {key!r}",
                dep=dep_name,
                field=key,
            )
        return val

    if kind == "git":
        raw_sid: SourceId = GitSourceId(url=_req("url"), subpath=fields.get("subpath"))
    elif kind == "oci":
        raw_sid = OciSourceId(
            registry=_req("registry"),
            repository=_req("repository"),
            subpath=fields.get("subpath"),
        )
    elif kind == "tarball":
        raw_sid = TarballSourceId(url=_req("url"), subpath=fields.get("subpath"))
    elif kind == "local":
        raw_sid = LocalSourceId(path=_req("path"))
    elif kind == "registry":
        raw_sid = RegistrySourceId(
            registry=_req("registry"),
            namespace=fields.get("namespace"),
            name=_req("name"),
        )
    elif kind == "member":
        raw_sid = MemberSourceId(member_name=_req("name"))
    else:
        raise MilpaError(
            LOCK_SRC_KIND_UNKNOWN,
            f"dep {dep_name!r}: unknown source kind {kind!r} "
            f"(known: {', '.join(_SOURCE_KIND_LABELS)})",
            dep=dep_name,
            kind=kind,
        )

    return normalize_source(raw_sid)


def _parse_provenance_block(node: KdlNode, dep_name: str) -> ProvenanceRecord:
    """Parse a ``provenance { ... }`` block into a ProvenanceRecord."""
    # Collect all scalar child fields into a dict; handle submodule nodes specially.
    fields: dict[str, str] = {}
    submodule_shas: dict[str, str] = {}
    for child in node_children(node):
        cname = node_name(child)
        # H5: submodule nodes have the form:
        #   submodule "<path>" sha="<40hex>"
        # They have ONE positional arg (path) and ONE property (sha).
        if cname == "submodule":
            child_args = node_args(child)
            if len(child_args) != 1:
                raise MilpaError(
                    LOCK_SUBMODULE_FIELD_INVALID,
                    f"dep {dep_name!r}: submodule node must have exactly one "
                    f"positional arg (path), got {len(child_args)}",
                    dep=dep_name,
                    field="submodule",
                )
            sub_path = value_as_str(child_args[0])
            if sub_path is None:
                raise MilpaError(
                    LOCK_SUBMODULE_FIELD_INVALID,
                    f"dep {dep_name!r}: submodule path must be a string",
                    dep=dep_name,
                    field="submodule",
                )
            sub_sha = node_prop_str(child, "sha")
            if sub_sha is None:
                raise MilpaError(
                    LOCK_SUBMODULE_FIELD_INVALID,
                    f"dep {dep_name!r}: submodule {sub_path!r} missing required sha= property",
                    dep=dep_name,
                    field="submodule",
                )
            submodule_shas[sub_path] = sub_sha
            continue

        child_args = node_args(child)
        if len(child_args) != 1:
            raise MilpaError(
                LOCK_PROV_FIELD_ARITY,
                f"dep {dep_name!r}: provenance field {cname!r} must have "
                f"exactly one value, got {len(child_args)}",
                dep=dep_name,
                field=cname,
            )
        raw = child_args[0]
        s = value_as_str(raw)
        if s is None:
            raise MilpaError(
                LOCK_PROV_FIELD_ARITY,
                f"dep {dep_name!r}: provenance field {cname!r} must be a "
                f"string, got {raw!r}",
                dep=dep_name,
                field=cname,
            )
        fields[cname] = s

    # kind discriminator is required
    kind = fields.get("kind")
    if kind is None:
        raise MilpaError(
            LOCK_PROV_KIND_MISSING,
            f"dep {dep_name!r}: provenance block missing 'kind' discriminator",
            dep=dep_name,
        )

    # origin field: required (S3 purge: no default; raises LOCK-PROV-FIELD-MISSING if absent)
    origin = _req_field(fields, "origin", dep_name)

    if kind == "git":
        return GitProvenanceRecord(
            url=_req_field(fields, "url", dep_name),
            ref=fields.get("ref"),
            commit_sha=fields.get("commit_sha"),
            submodule_shas=submodule_shas,
            origin=origin,
        )
    if kind == "tarball":
        return TarballProvenanceRecord(
            url=_req_field(fields, "url", dep_name),
            sha256=fields.get("sha256"),
            origin=origin,
        )
    if kind == "local":
        return LocalProvenanceRecord(
            path=_req_field(fields, "path", dep_name),
            origin=origin,
        )
    if kind == "member":
        return MemberProvenanceRecord(
            name=_req_field(fields, "name", dep_name),
            origin=origin,
        )
    if kind == "oci":
        return OciProvenanceRecord(
            registry=_req_field(fields, "registry", dep_name),
            repository=_req_field(fields, "repository", dep_name),
            digest=_req_field(fields, "digest", dep_name),
            origin=origin,
        )
    if kind == "root":
        return RootProvenanceRecord(
            name=_req_field(fields, "name", dep_name),
            origin=origin,
        )

    raise MilpaError(
        LOCK_PROV_KIND_UNKNOWN,
        f"dep {dep_name!r}: unknown provenance kind {kind!r} "
        f"(known: git, tarball, local, member, oci, root)",
        dep=dep_name,
        kind=kind,
    )


def _req_field(fields: dict[str, str], key: str, dep_name: str) -> str:
    """Return a required provenance field, raising LOCK-PROV-FIELD-MISSING if absent."""
    val = fields.get(key)
    if val is None:
        raise MilpaError(
            LOCK_PROV_FIELD_MISSING,
            f"dep {dep_name!r}: provenance missing required field {key!r}",
            dep=dep_name,
            field=key,
        )
    return val


