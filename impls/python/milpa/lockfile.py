def _req_name_to_lockfile(s: str) -> str:
    """Convert a ``requires`` entry from solver-var form to lockfile-safe form.

    Solver-internally qualified deps are keyed by ``"ns::name"`` (the solver
    variable).  The lockfile serializes the same relationship as ``"ns/name"``
    (slash-separated, Windows-safe, mirrors the manifest declaration syntax).

    Bare dep names (no ``::`` separator) are returned unchanged.

    This is the SOLE conversion site — called from ``_locked_from_resolved``.
    """
    if "::" in s:
        ns, _, name = s.partition("::")
        return f"{ns}/{name}"
    return s


def from_graph(
    graph: ResolvedGraph,
    *,
    strategy: str = "maxver",
    exclude_newer: datetime | None = None,
) -> Lockfile:
    """Convert a ResolvedGraph into a Lockfile.

    Deps are sorted by ``(namespace or "", name)`` so that two qualified deps
    with the same bare name (e.g. ``ns1::bar`` and ``ns2::bar``) land in a
    stable, deterministic order (lockfile-schema.md §2.3 + §2.4 +
    resolver-semantics.md §4.4). Same graph always produces byte-identical
    lockfile text.

    ``exclude_newer`` (D5, resolution-semantics RFC §3 Axis D / §5): the
    EFFECTIVE time-bound this resolve ran under, recorded verbatim into the
    lockfile's top-level ``exclude_newer`` node (``None`` ⇒ the node is
    omitted entirely by ``format_lockfile`` — never a sentinel timestamp).
    """
    deps = tuple(
        sorted(
            (_locked_from_resolved(d) for d in graph.deps),
            key=lambda d: (d.namespace or "", d.name),
        )
    )
    return Lockfile(deps=deps, strategy=strategy, exclude_newer=exclude_newer)


def _locked_from_resolved(d: ResolvedDep) -> LockedDep:
    """Translate a ResolvedDep into a LockedDep."""
    return LockedDep(
        name=d.name,
        identity=d.identity,
        version=d.version,
        src_dir=d.src_dir,
        # Sort lexicographically — requires is accumulated in BFS arrival order
        # which is non-deterministic across parallel-fetch runs. Lexicographic
        # order is the spec's single canonical ordering rule (§3.4 / §4.4).
        # C1: convert solver_var form ("ns::name") to lockfile-safe slash form
        # ("ns/name") — solver vars must not appear in the lockfile (§1.7.1).
        requires=tuple(sorted(_req_name_to_lockfile(r) for r in d.requires)),
        provenances=d.provenances,
        active_flags=d.active_flags,
        # S6: carry the dep_decl hash from the resolver through to the lockfile pin.
        dep_decl=d.dep_decl,
        # S4: carry cond_requires (sorted by (name, canonical-predicate-string)).
        cond_requires=d.cond_requires,
        # Phase B: carry dedup aliases from ResolvedDep (lex-sorted by dedup pass).
        aliases=d.aliases,
        # C1: carry namespace for qualified named deps (None for all others).
        namespace=d.namespace,
        # RFC per-entry-attestation.md P2: narrow EntryAttestation (index-side,
        # carries bundle_pin) to LockAttestation (lockfile-side, no bundle_pin —
        # lockfile-schema.md §3.9 NORMATIVE excludes the delivery pin).
        attestation=(
            LockAttestation(
                kind=d.attestation.kind,
                rekor=d.attestation.rekor,
                bundle_pin=d.attestation.bundle_pin,
                # RFC origin-as-identity.md §4.4 (B2/G10): derive from
                # source_id.namespace (the SAME real index namespace) rather
                # than the deleted registry_namespace field.
                namespace=(
                    d.source_id.namespace or ""
                    if isinstance(d.source_id, RegistrySourceId)
                    else ""
                ),
            )
            if d.attestation is not None
            else None
        ),
        # A5: sibling source for the declared version — carried straight
        # through, never recomputed at the lockfile boundary.
        declared_version_source=d.declared_version_source,
        # RFC origin-as-identity.md §4.1/§7 (S5): carry the binding phase's
        # accepted SourceId straight through to the on-disk structured form.
        source_id=d.source_id,
    )


# ---------------------------------------------------------------------------
# Predicate-name whitelist (M1: validate untrusted lockfile keys)
#
# Only these keys are accepted when PARSING a cond-require node from a
# (potentially attacker-controlled) lockfile.  Keys outside the set are
# silently dropped (forward-compat lenient, same spirit as "skip unknown
# child nodes").  The whitelist must stay in sync with spec/lockfile-schema.md
# §3.5 and manifest-grammar.md §6.
_KNOWN_PREDICATE_NAMES: frozenset[str] = frozenset(
    {"platform", "arch", "nim", "milpa", "flag"}
)

# ---------------------------------------------------------------------------
# _kdl_str — SSOT for string escaping (lockfile-schema.md §2.4)
#
# Escapes: \ → \\, " → \", control chars U+0000–U+001F → \u{NNNN},
# everything else verbatim. No named escapes (\n, \t, etc.) — the spec
# says "\u{NNNN}" for all control chars; for simplicity we use the unicode
# escape form for all U+0000–U+001F uniformly.
# ---------------------------------------------------------------------------

_CTRL_ESCAPES: dict[str, str] = {
    "\\": "\\\\",
    '"': '\\"',
}


def _kdl_str(s: str) -> str:
    r"""Return ``s`` as a double-quoted, KDL 2.0-escaped string literal.

    SSOT for string escaping in the lockfile emitter. Every string value
    emitted by ``format_lockfile`` passes through this function.

    Escape rules (lockfile-schema.md §2.4):
      \\  →  \\\\  (backslash escape)
      "   →  \\"   (double-quote escape)
      U+0000–U+001F → \u{NNNN}  (control chars in hex)
      everything else → verbatim (valid KDL 2.0 string content)
    """
    out: list[str] = []
    for ch in s:
        esc = _CTRL_ESCAPES.get(ch)
        if esc is not None:
            out.append(esc)
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _format_predicate_prop(pred: Predicate) -> str:
    """Emit one predicate as ``key="value"`` or ``key=(not)"value"`` (RFC §3.4.1).

    The prop key is ``pred.name``; value is ``pred.values[0]`` (every predicate
    produced by this pipeline is single-value — v0 invariant per spec §3.5 /
    lockfile-schema §3.5). Multi-value (OR) predicates are not supported in v0;
    the guard below enforces the invariant so violations surface as an explicit
    error rather than silently truncating values[1:] (and are not stripped under
    ``python -O`` as a bare ``assert`` would be).
    Negation uses the KDL type-annotation form ``(not)"value"`` — verbatim from
    ``manifest-grammar.md §6``.
    """
    if len(pred.values) != 1:
        raise ValueError(
            f"_format_predicate_prop: predicate {pred.name!r} has {len(pred.values)} values "
            f"but only single-value predicates are supported in v0 (spec §3.5). "
            f"Multi-value (OR) emission is not implemented."
        )
    val = _kdl_str(pred.values[0])
    if pred.negated:
        return f'{pred.name}=(not){val}'
    return f'{pred.name}={val}'


def cond_require_sort_key(cr: "CondRequire") -> "tuple[str, str]":
    """Total sort key for a ``CondRequire``: ``(name, canonical-predicate-string)``.

    Using name alone is NOT a total order when same-name entries exist (a dep in
    ≥2 when-branches).  The predicate string makes the key total and deterministic
    across impls regardless of source order (C1 fix, §2.4).

    The per-predicate string is built by calling ``_format_predicate_prop`` so
    that KDL string escaping is shared with the emitter — sort order cannot drift
    from emission order even if a predicate value ever contains ``"`` or ``\\``.
    """
    pred_strs = ",".join(_format_predicate_prop(p) for p in cr.predicates)
    return (cr.name, pred_strs)


def _format_cond_require(cr: "CondRequire") -> list[str]:
    """Emit a ``cond-require`` node (RFC §3.4.1).

    Single predicate → inline property form:
        ``    cond-require "name" key="value"``

    Multiple predicates (AND) → block form:
        ``    cond-require "name" {``
        ``        when key="value"``
        ``        ...``
        ``    }``
    """
    name_str = _kdl_str(cr.name)
    if len(cr.predicates) == 1:
        prop = _format_predicate_prop(cr.predicates[0])
        return [f"    cond-require {name_str} {prop}"]
    else:
        out = [f"    cond-require {name_str} {{"]
        for pred in cr.predicates:
            prop = _format_predicate_prop(pred)
            out.append(f"        when {prop}")
        out.append("    }")
        return out


def _format_lock_attestation(att: LockAttestation) -> list[str]:
    """Emit the ``attestation { kind; signer; rekor { … } }`` block (§3.9).

    ``signer`` is emitted only for ``AuthorSigned`` (absent for
    ``MilpaVendored`` — mirrors the source index record's structural
    invariant). The nested ``rekor`` block is omitted entirely when the
    source index entry carried none.
    """
    out = ["    attestation {"]
    if isinstance(att.kind, AuthorSigned):
        out.append(f'        kind {_kdl_str("author-signed")}')
        out.append(f"        signer {_kdl_str(att.kind.signer)}")
    else:
        out.append(f'        kind {_kdl_str("milpa-vendored")}')
    if att.rekor is not None:
        out.append("        rekor {")
        out.append(f"            uuid {_kdl_str(att.rekor.uuid)}")
        out.append(f"            log_index {_kdl_str(att.rekor.log_index)}")
        out.append(f"            integrated_time {_kdl_str(att.rekor.integrated_time)}")
        out.append("        }")
    if att.bundle_pin is not None:
        # P3a: delivery-integrity pin (lockfile-schema.md §3.9 P3a addition).
        out.append(f"        bundle sha256={_kdl_str(att.bundle_pin)}")
    # P3a: the entry's REAL index namespace — always emitted (mandatory, like
    # `kind`), even when empty (an unqualified index entry legitimately has
    # namespace ""); needed by milpa verify's offline re-verification (§7)
    # to rebuild the exact subject coordinate with no index available.
    out.append(f"        namespace {_kdl_str(att.namespace)}")
    out.append("    }")
    return out


def format_lockfile(lockfile: Lockfile) -> str:
    """Render a ``Lockfile`` to byte-exact KDL 2.0 text.

    Implements the canonical serialization rules from lockfile-schema.md §2.4.
    The output is deterministic: same logical lockfile → identical bytes.

    Layout:
      1. Header comment
      2. ``version 1`` (integer, unquoted)
      3. ``strategy "<name>"``
      3a. ``exclude_newer "<ts>"`` (D5, OPTIONAL — emitted only when set)
      4. Blank line
      5. dep blocks (lexicographic order), each followed by blank line
      6. File ends with the blank line after the last dep block (last byte = 0x0A)
    """
    lines: list[str] = [
        _HEADER,
        f"version {lockfile.version}",
        f"strategy {_kdl_str(lockfile.strategy)}",
    ]
    # D5 (resolution-semantics RFC §3 Axis D / §5): optional top-level
    # exclude_newer node — emitted only when the effective time-bound was
    # set (never a sentinel), positioned right after strategy and before
    # the blank line separating the header from the dep blocks.
    if lockfile.exclude_newer is not None:
        lines.append(
            f"exclude_newer {_kdl_str(_format_resolution_timestamp(lockfile.exclude_newer))}"
        )
    lines.append("")
    for dep in lockfile.deps:
        lines.append(f"dep {_kdl_str(dep.name)} {{")
        # C1: namespace child node — emitted FIRST when non-None (§3.9).
        # ``dep "bar" { namespace "ns1"; ... }`` — bare name as arg, ns as child.
        if dep.namespace is not None:
            lines.append(f"    namespace {_kdl_str(dep.namespace)}")
        # source — RFC origin-as-identity.md §4.1/§7 (S5): the structured
        # on-disk SourceId, typed children (uv's model). Positioned right
        # after namespace, before identity: "where this came from" before
        # "what its content hash is". Omitted only for a lockfile predating
        # S5 (forward-compat; a conformant S5+ emitter always writes it).
        if dep.source_id is not None:
            lines.append("    source {")
            for sline in _format_source_fields(dep.source_id):
                lines.append(f"        {sline}")
            lines.append("    }")
        # identity — emitted only when not None
        if dep.identity is not None:
            lines.append(f"    identity {_kdl_str(dep.identity)}")
        lines.append(f"    version {_kdl_str(dep.version)}")
        # A5: declared_version_source — the sibling field to version, emitted
        # only when a source exists (a version-unknown dep's "0.0.0" carries
        # no source at all, §5 NORMATIVE — the unambiguous boundary pairing).
        if dep.declared_version_source is not None:
            lines.append(
                f"    declared_version_source {_kdl_str(dep.declared_version_source)}"
            )
        lines.append(f"    src_dir {_kdl_str(dep.src_dir)}")
        # requires — always emitted; bare when empty, args when non-empty
        if dep.requires:
            req_args = " ".join(_kdl_str(r) for r in dep.requires)
            lines.append(f"    requires {req_args}")
        else:
            lines.append("    requires")
        # cond-require — S4: additive annotation nodes.
        # Emitted immediately after requires. Omitted when empty (byte-identical
        # for deps with no conditional requires). Sort at emission for
        # determinism (lockfile-schema.md §2.4 / RFC §3.4.1).
        # Delegates to cond_require_sort_key (module-level SSOT) so escaping
        # is shared with _format_predicate_prop and cannot drift (C1 fix).
        for cr in sorted(dep.cond_requires, key=cond_require_sort_key):
            lines.extend(_format_cond_require(cr))
        # aliases — Phase B dedup: alternate names for deduped deps (§3.8).
        # Omitted entirely when empty; args are lex-sorted by convention.
        if dep.aliases:
            alias_args = " ".join(_kdl_str(a) for a in sorted(dep.aliases))
            lines.append(f"    aliases {alias_args}")
        # active_flags — omitted when empty
        if dep.active_flags:
            flag_args = " ".join(_kdl_str(f) for f in dep.active_flags)
            lines.append(f"    active_flags {flag_args}")
        # attestation — per-entry Layer 2 claim (§3.9). Positioned after
        # active_flags, before provenance blocks (lockfile-schema.md §2.4).
        if dep.attestation is not None:
            lines.extend(_format_lock_attestation(dep.attestation))
        # dep_decl pin — S6: emitted only when present (forward-compat additive)
        if dep.dep_decl is not None:
            lines.append(f"    dep_decl {_kdl_str(dep.dep_decl)}")
        # provenance blocks — sorted by canonical key (§4.0): declared < observed;
        # git < tarball < oci < local < member < root; then (primary, secondary).
        for prov in sorted(dep.provenances, key=_provenance_sort_key):
            lines.append("    provenance {")
            for pline in _format_provenance_fields(prov):
                lines.append(f"        {pline}")
            lines.append("    }")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def _format_source_fields(sid: SourceId) -> list[str]:
    """Emit ``kind`` + kind-specific typed children for a ``source { … }``
    block (RFC origin-as-identity.md §4.1/§7, S5 — NORMATIVE, both impls
    MUST match byte-for-byte).

    Field order per kind:
      git:      kind / url / subpath?
      oci:      kind / registry / repository / subpath?
      tarball:  kind / url / subpath?
      local:    kind / path
      registry: kind / registry / namespace? / name
      member:   kind / name

    URL-bearing fields carry the ``(url)`` KDL type annotation
    ([[kdl_url_convention]]); the parser reads the string content regardless
    of tag.
    """
    if isinstance(sid, GitSourceId):
        out = [f'kind {_kdl_str("git")}', f"url (url){_kdl_str(sid.url)}"]
        if sid.subpath is not None:
            out.append(f"subpath {_kdl_str(sid.subpath)}")
        return out
    if isinstance(sid, OciSourceId):
        out = [
            f'kind {_kdl_str("oci")}',
            f"registry {_kdl_str(sid.registry)}",
            f"repository {_kdl_str(sid.repository)}",
        ]
        if sid.subpath is not None:
            out.append(f"subpath {_kdl_str(sid.subpath)}")
        return out
    if isinstance(sid, TarballSourceId):
        out = [f'kind {_kdl_str("tarball")}', f"url (url){_kdl_str(sid.url)}"]
        if sid.subpath is not None:
            out.append(f"subpath {_kdl_str(sid.subpath)}")
        return out
    if isinstance(sid, LocalSourceId):
        return [f'kind {_kdl_str("local")}', f"path {_kdl_str(sid.path)}"]
    if isinstance(sid, RegistrySourceId):
        out = [f'kind {_kdl_str("registry")}', f"registry {_kdl_str(sid.registry)}"]
        if sid.namespace is not None:
            out.append(f"namespace {_kdl_str(sid.namespace)}")
        out.append(f"name {_kdl_str(sid.name)}")
        return out
    if isinstance(sid, MemberSourceId):
        return [f'kind {_kdl_str("member")}', f"name {_kdl_str(sid.member_name)}"]
    raise TypeError(f"unrecognized SourceId variant: {type(sid)!r}")  # pragma: no cover


def _format_provenance_fields(p: ProvenanceRecord) -> list[str]:
    """Emit origin + kind + kind-specific fields for a provenance block.

    Field order per kind (lockfile-schema.md §2.4, D-provenance amendment):
      all kinds: origin (ALWAYS first) / kind (second) / kind-specific fields
      git:      origin / kind / url / ref / commit_sha
      tarball:  origin / kind / url / sha256
      local:    origin / kind / path
      member:   origin / kind / name
      oci:      origin / kind / registry / repository / digest
      root:     origin / kind / name

    origin is ALWAYS emitted (never omitted), regardless of value.
    Optional fields (ref, commit_sha, sha256) are omitted when None.
    """
    # origin is always first, always emitted.
    out = [f"origin {_kdl_str(p.origin)}", f"kind {_kdl_str(p.kind)}"]
    if isinstance(p, GitProvenanceRecord):
        out.append(f"url {_kdl_str(p.url)}")
        if p.ref is not None:
            out.append(f"ref {_kdl_str(p.ref)}")
        if p.commit_sha is not None:
            out.append(f"commit_sha {_kdl_str(p.commit_sha)}")
        # H5: emit submodule child nodes (path-sorted for deterministic diffs).
        for sub_path, sub_sha in sorted(p.submodule_shas.items()):
            out.append(f"submodule {_kdl_str(sub_path)} sha={_kdl_str(sub_sha)}")
    elif isinstance(p, TarballProvenanceRecord):
        out.append(f"url {_kdl_str(p.url)}")
        if p.sha256 is not None:
            out.append(f"sha256 {_kdl_str(p.sha256)}")
    elif isinstance(p, LocalProvenanceRecord):
        out.append(f"path {_kdl_str(p.path)}")
    elif isinstance(p, MemberProvenanceRecord):
        out.append(f"name {_kdl_str(p.name)}")
    elif isinstance(p, OciProvenanceRecord):
        out.append(f"registry {_kdl_str(p.registry)}")
        out.append(f"repository {_kdl_str(p.repository)}")
        out.append(f"digest {_kdl_str(p.digest)}")
    elif isinstance(p, RootProvenanceRecord):
        out.append(f"name {_kdl_str(p.name)}")
    return out


def write_lockfile(lockfile: Lockfile, path: Path) -> Path:
    """Write lockfile KDL text to ``path`` atomically.  Returns the path.

    Atomic discipline: format the content, write to a sibling temp file in the
    same directory as *path*, then ``os.replace(tmp, path)`` — a POSIX atomic
    rename.  The temp file lives in the target's parent so the rename is
    always same-filesystem; EXDEV (cross-device rename failure) is structurally
    impossible.  If formatting or the write raises, the temp file is removed
    and the exception propagates — no temp files are ever left behind.
    """
    import contextlib
    import os

    path.parent.mkdir(parents=True, exist_ok=True)
    # Build a unique temp name in the same directory as the target.
    tmp = path.with_suffix(path.suffix + f".tmp.{os.getpid()}")
    try:
        tmp.write_text(format_lockfile(lockfile), encoding="utf-8")
        os.replace(tmp, path)
    except Exception:
        with contextlib.suppress(OSError):
            tmp.unlink(missing_ok=True)
        raise
    return path


def load_lockfile(path: Path) -> Lockfile:
    """Read and parse a lockfile from disk.

    Raises ``MilpaError(LOCK_FILE_NOT_FOUND)`` / ``MilpaError(LOCK_FILE_UNREADABLE)``
    on I/O failure.
    """
    from milpa.errors import LOCK_FILE_NOT_FOUND, LOCK_FILE_UNREADABLE

    try:
        text = path.read_text()
    except FileNotFoundError as exc:
        raise MilpaError(
            LOCK_FILE_NOT_FOUND,
            f"lockfile not found: {path}",
            path=str(path),
        ) from exc
    except OSError as exc:
        raise MilpaError(
            LOCK_FILE_UNREADABLE,
            f"cannot read lockfile {path}: {exc}",
            path=str(path),
        ) from exc
    return parse_lockfile(text)


