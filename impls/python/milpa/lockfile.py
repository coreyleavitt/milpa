# ProvenanceRecord — 6 variants + 1 read-compat (lockfile-schema.md §4)
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class GitProvenanceRecord:
    """Provenance for a git-fetched dep (§4.1).

    url is required. ref and commit_sha are optional — omitted when None.
    commit_sha is the resolved SHA from the fetch receipt, not the manifest ref.
    origin: "observed" (milpa fetched+verified) or "declared" (claimed mirror,
    unverified until first use). Default "observed". Per-lockfile annotation —
    never a CAS-entry property.

    submodule_shas: H5 provenance — {path → sha} for each recursed submodule
    (lockfile-schema.md §4.1). Empty dict when no submodules. These are KDL
    child nodes ``submodule "<path>" sha="<40hex>"``, path-sorted.
    """

    url: str
    ref: str | None = None
    commit_sha: str | None = None
    submodule_shas: dict[str, str] = field(default_factory=dict)
    origin: str = "observed"
    kind: str = field(default="git", init=False)


@dataclass(frozen=True)
class TarballProvenanceRecord:
    """Provenance for a tarball-fetched dep (§4.2).

    url is required. sha256 is optional on first fetch (TOFU model — §5);
    once pinned it is preserved on all subsequent lockfile writes.
    sha256 records the archive hash (transport integrity), NOT the identity
    (source-tree hash). These are orthogonal fields.
    origin: "observed" or "declared". Default "observed".
    """

    url: str
    sha256: str | None = None
    origin: str = "observed"
    kind: str = field(default="tarball", init=False)


@dataclass(frozen=True)
class LocalProvenanceRecord:
    """Provenance for a local-path dep (§4.3).

    path is the as-declared relative path from the project root. NOT resolved
    to absolute — portability across machines with the same workspace layout.
    origin: "observed" or "declared". Default "observed".
    """

    path: str
    origin: str = "observed"
    kind: str = field(default="local", init=False)


@dataclass(frozen=True)
class MemberProvenanceRecord:
    """Provenance for a workspace-internal member reference (§4.4).

    origin: "observed" or "declared". Default "observed".
    """

    name: str
    origin: str = "observed"
    kind: str = field(default="member", init=False)


@dataclass(frozen=True)
class OciProvenanceRecord:
    """Provenance for an OCI-artifact dep (§4.5).

    All three fields are required. digest is the immutable content-addressed
    pin (e.g. sha256:…).
    origin: "observed" or "declared". Default "observed".
    """

    registry: str
    repository: str
    digest: str
    origin: str = "observed"
    kind: str = field(default="oci", init=False)


@dataclass(frozen=True)
class RootProvenanceRecord:
    """Provenance for a transitive reference to the resolving STANDALONE
    root's own name (resolver-semantics.md §14 "root satisfies its own name").

    A standalone package is a workspace-of-one: when some transitive dep's
    own manifest requires the root's own declared name, the root itself
    satisfies that reference — never a second, separately-fetched copy.
    This is the non-workspace analog of ``member`` (§4.4); deliberately a
    DISTINCT kind (not a reuse of ``member``) because ``frozen.py``'s
    ``FROZEN-MEMBER-DEP`` guard hard-rejects a ``member``-kind provenance in
    a single-package (non-workspace) lockfile — conflating the two would
    trip that invariant.

    origin: always "observed" — the root is never a "declared" mirror
    source (it is not a mirror at all).
    """

    name: str
    origin: str = "observed"
    kind: str = field(default="root", init=False)


#: Discriminated union of all provenance record variants.
ProvenanceRecord = (
    GitProvenanceRecord
    | TarballProvenanceRecord
    | LocalProvenanceRecord
    | MemberProvenanceRecord
    | OciProvenanceRecord
    | RootProvenanceRecord
)

