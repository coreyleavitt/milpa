"""milpa.lock — reproducible-build snapshot of a resolved dep graph.

Owns:
  - ProvenanceRecord discriminated union (6 variants)
  - LockedDep, Lockfile — lockfile data model
  - ResolvedDep, ResolvedGraph — resolver output types (owned here to avoid
    forward-import cycles: resolver.py imports and *produces* these types;
    lockfile.py owns them so from_graph/verify need no fetcher/resolver import)
  - parse_lockfile(text) -> Lockfile
  - from_graph(graph, *, strategy) -> Lockfile
  - format_lockfile(lock) -> str  — byte-exact hand-rolled templating (SSOT)
  - verify_against_graph(lockfile, graph) -> None
  - verify_lockfile_against_deps(lockfile, deps_dir) -> list[str]

Layering: lockfile.py ← resolver.py (resolver imports ResolvedDep/ResolvedGraph
from lockfile, not the other way). See RFC §4.2.

Format: KDL 2.0 via kdl_io.parse_kdl(text, context="lockfile") for parsing.
Emission is hand-rolled string templating — the lockfile NEVER goes through a
KDL AST emitter. _kdl_str is the single source of truth for string escaping.

ProvenanceRecord kinds (lockfile-schema.md §4):
    git      — §4.1: url (req), ref (opt), commit_sha (opt)
    tarball  — §4.2: url (req), sha256 (opt, TOFU receipt)
    local    — §4.3: path (req, as-declared relative)
    member   — §4.4: name (req, workspace member name)
    oci      — §4.5: registry/repository/digest (all req)
    root     — resolver-semantics.md §14: name (req) — a transitive dep's
               reference to the resolving STANDALONE root's own name,
               satisfied by the root itself (never a second fetched copy).
               A standalone package is a workspace-of-one; `root` is the
               non-workspace analog of `member`.
"""

