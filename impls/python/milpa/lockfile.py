def verify_against_graph(
    lockfile: Lockfile,
    graph: ResolvedGraph,
) -> None:
    """Verify that the resolved graph matches the lockfile dep-for-dep.

    Checks (lockfile-schema.md §6.1):
      - Every dep in the graph has a corresponding lockfile entry (by name).
      - Every dep in the lockfile has a corresponding graph entry.
      - For every dep in both: identity fields match exactly.

    Raises ``MilpaError(LOCK_GRAPH_MISMATCH)`` on any divergence.
    Collects ALL mismatches before raising (not fail-fast).
    """
    # C1: key by dep_dir_name (namespace-aware) so two qualified deps with the
    # same bare name (e.g. ns1/bar and ns2/bar) are distinct in the index.
    locked_by_name = {dep_dir_name(d.name, d.namespace): d for d in lockfile.deps}
    graph_by_name = {dep_dir_name(d.name, d.namespace): d for d in graph.deps}

    errors: list[str] = []
    for name in sorted(graph_by_name.keys() - locked_by_name.keys()):
        errors.append(
            f"dep {name!r} is in the resolved graph but absent from the lockfile"
        )
    for name in sorted(locked_by_name.keys() - graph_by_name.keys()):
        errors.append(
            f"dep {name!r} is in the lockfile but absent from the resolved graph"
        )
    for name in sorted(graph_by_name.keys() & locked_by_name.keys()):
        locked = locked_by_name[name]
        actual = graph_by_name[name]
        if locked.identity != actual.identity:
            errors.append(
                f"dep {name!r}: identity mismatch — "
                f"lockfile={locked.identity!r}, graph={actual.identity!r}"
            )

    if errors:
        raise MilpaError(
            LOCK_GRAPH_MISMATCH,
            "lockfile does not match resolved graph:\n  " + "\n  ".join(errors),
            mismatches=errors,
        )


def check_locked_drift(
    prior: "Lockfile | None",
    graph: ResolvedGraph,
    exclude_newer: datetime | None = None,
) -> None:
    """``--locked`` guard (resolution-semantics RFC §3 Axis B / §6 D-B2).

    ``--locked`` always performs a REAL resolve (with the B2 minimal-change/
    prior-lock preference already applied via ``prior``) and then asserts the
    result is IDENTICAL to the committed lock — distinct from ``frozen``,
    which skips solving entirely and only reconstructs.

    **Drift is identity-based (D-B2), never version-label-based:** the
    comparison keys on ``identity`` (content hash) + the canonicalized
    ``provenances`` set only. The version string is deliberately NEVER
    consulted — the one-time Axis-A ``0.0.1``→real-declared-version relabel
    of an identity-unchanged git/url/local/tarball dep is therefore
    compatible, not drift.

    Provenances are compared after sorting each side by the same canonical
    ``_provenance_sort_key`` the emitter uses (lockfile-schema.md §4.0) —
    ``graph.deps[i].provenances`` is observed-first/unsorted (sorted only at
    KDL emission time), while ``prior.deps[i].provenances`` was parsed back
    from already-canonically-sorted text, so comparing raw tuple order would
    produce false-positive drift.

    ``exclude_newer`` (D5, §6 D-D3 no-silent-drop) is the EFFECTIVE
    ``exclude_newer`` this ``--locked`` resolve just ran under. Dropping a
    previously-recorded bound RELAXES semantics (silently un-freezes the
    project), so — unlike identity/provenance, which are compared per-dep
    above — this is a single whole-lockfile comparison: ``prior.
    exclude_newer`` present but the new effective value absent (or a
    genuinely different timestamp) is drift.

    Raises ``MilpaError(RES_LOCKED_DRIFT)`` naming every drifted/added/
    removed package, or — when ``prior`` is ``None`` — because there is no
    committed lockfile to reproduce against at all (a best-in-class CI guard
    cannot assert reproducibility with nothing to reproduce).
    """
    if prior is None:
        raise MilpaError(
            RES_LOCKED_DRIFT,
            "--locked requires a committed milpa.lock to verify against, but "
            "none was found; run `milpa lock` (or `milpa fetch`/`milpa lock` "
            "without --locked) to create one",
        )

    locked_by_name = {dep_dir_name(d.name, d.namespace): d for d in prior.deps}
    graph_by_name = {dep_dir_name(d.name, d.namespace): d for d in graph.deps}

    drifted: list[str] = []
    for name in sorted(graph_by_name.keys() - locked_by_name.keys()):
        drifted.append(
            f"{name}: added — resolved but absent from the committed lockfile"
        )
    for name in sorted(locked_by_name.keys() - graph_by_name.keys()):
        drifted.append(
            f"{name}: removed — present in the committed lockfile, absent from the resolve"
        )
    for name in sorted(graph_by_name.keys() & locked_by_name.keys()):
        locked = locked_by_name[name]
        actual = graph_by_name[name]
        # D-B2: identity + provenance ONLY — the version label is never
        # consulted (a version relabel with unchanged identity is not drift).
        if locked.identity != actual.identity:
            drifted.append(
                f"{name}: identity changed — "
                f"lockfile={locked.identity!r}, resolve={actual.identity!r}"
            )
            continue
        locked_provs = tuple(sorted(locked.provenances, key=_provenance_sort_key))
        actual_provs = tuple(sorted(actual.provenances, key=_provenance_sort_key))
        if locked_provs != actual_provs:
            drifted.append(
                f"{name}: provenance changed — "
                f"lockfile={locked_provs!r}, resolve={actual_provs!r}"
            )

    # D5 (§6 D-D3 no-silent-drop): a dropped or changed exclude_newer bound
    # is drift too, compared once for the whole lockfile (not per-dep).
    if prior.exclude_newer != exclude_newer:
        drifted.append(
            f"exclude_newer: changed — lockfile={prior.exclude_newer!r}, "
            f"resolve={exclude_newer!r}"
        )

    if drifted:
        raise MilpaError(
            RES_LOCKED_DRIFT,
            "--locked: resolved graph deviates from the committed lockfile:\n  "
            + "\n  ".join(drifted),
            drifted=drifted,
        )


def _classify_dep_path(dep_path: Path) -> str | None:
    """Classify a ``_deps/<name>`` path into one of four states.

    Returns a divergence string if the path is in states (b), (c), or (d);
    returns None if the path is in state (a) (symlink present + store readable).

    States (RFC rfc-content-addressed-identity.md Phase C §6 item 6):
      (a) symlink present + store entry readable ⇒ None (pass)
      (b) dangling symlink (is_symlink() true, exists() false) ⇒ "dangling" divergence
      (c) symlink resolves but store read raises OSError ⇒ CAS-STORE-IO-ERROR divergence
      (d) no entry at all (not a symlink, not exists) ⇒ "missing" divergence

    Note: non-symlink directories/files that *do* exist fall through to (a) and
    are handled by the caller's is_dir() + identity-hash checks.
    """
    name = dep_path.name
    is_link = dep_path.is_symlink()
    exists = dep_path.exists()  # follows symlinks

    if is_link and not exists:
        # State (b): dangling symlink — store entry GC'd or store not mounted.
        return (
            f"{name}: dangling symlink — store entry gone or store not mounted "
            f"(target: {dep_path})"
        )

    if not is_link and not exists:
        # State (d): genuinely absent — nothing at _deps/<name>.
        return f"{name}: missing from {dep_path.parent}/"

    # is_link && exists, OR !is_link && exists (plain dir/file):
    # Both cases proceed to identity hashing. If the hash raises an OSError,
    # that is state (c).
    return None  # Not a structural failure; caller checks identity.


def _is_local_dep(locked: "LockedDep") -> bool:
    """Return True iff the dep has at least one LocalProvenanceRecord.

    Used by verify_lockfile_against_deps to dispatch on provenance kind
    (lockfile-schema.md §6.2 NORMATIVE: local → liveness-only; others →
    identity hash-compare).
    """
    return any(isinstance(p, LocalProvenanceRecord) for p in locked.provenances)


def _verify_local_dep_liveness(
    name: str,
    dep_path: Path,
) -> str | None:
    """Liveness check for a local-provenance dep (lockfile-schema.md §6.2.1).

    Returns a divergence string for states (b), (c), (d); returns None for
    state (a) (symlink present + target is a reachable directory).

    States:
      (a) symlink present + target dir reachable → None (pass)
      (b) dangling symlink (is_symlink true, exists false) → "dangling"
      (c) plain dir, not a symlink → "expected symlink, found directory"
      (d) no entry at all → "missing from"
    """
    is_link = dep_path.is_symlink()
    exists = dep_path.exists()  # follows symlinks

    if is_link and not exists:
        # State (b): dangling — source tree deleted or moved.
        return (
            f"{name}: dangling symlink — source tree gone or moved "
            f"(target: {dep_path})"
        )

    if not is_link and not exists:
        # State (d): genuinely absent.
        return f"{name}: missing from {dep_path.parent}/"

    if not is_link and exists:
        # State (c): plain directory (or file) — not a symlink.
        # This means the local dep was overwritten by a non-symlink entry
        # (e.g. copied by a git fetcher or manually extracted).
        return (
            f"{name}: expected symlink to source tree, found plain directory at {dep_path}"
        )

    # is_link && exists: state (a) — live symlink to an existing dir.
    return None


def verify_lockfile_against_deps(
    lockfile: Lockfile,
    deps_dir: Path,
) -> list[str]:
    """Verify every lockfile dep against ``deps_dir/<name>/`` on disk.

    Dispatches on provenance kind (lockfile-schema.md §6.2 NORMATIVE):

    - LOCAL deps: liveness-only check (§6.2.1) — symlink resolves to an
      existing directory. No content hash is computed or compared.
    - All other deps: four-state structural check + identity hash-compare
      (§6.2.2).

    Also checks:
      - For each alias in dep.aliases: ``_deps/<alias>`` must be a symlink
        pointing at the same store entry as the canonical. Absence, dangling,
        or wrong-target ⇒ VERIFY-ALIAS-SYMLINK-MISSING.
      - Any entry under ``deps_dir/`` (excluding hidden entries and declared
        alias names) that has no corresponding lockfile entry is extra.

    Returns a list of divergence strings (may be empty). Does NOT raise —
    the caller decides whether to treat divergences as a hard error.
    Collects ALL divergences before returning (not fail-fast).
    """
    import os as _os
    divergences: list[str] = []
    # C1: key by dep_dir_name (namespace-aware) so qualified deps are found
    # at ``_deps/@<ns>/<name>`` not ``_deps/<name>``.
    locked_by_dir = {dep_dir_name(d.name, d.namespace): d for d in lockfile.deps}

    # Build the set of all expected dir-names (canonical + alias) so the
    # extra-dep scan does not flag expected entries as unexpected.
    expected_dir_names: set[str] = set(locked_by_dir.keys())
    for locked in lockfile.deps:
        expected_dir_names.update(locked.aliases)

    for dir_name, locked in sorted(locked_by_dir.items()):
        dep_path = deps_dir / dir_name
        # Use the last path component as the display name in error messages.
        name = locked.name

        # --- dispatch on provenance kind (§6.2 NORMATIVE) ---
        if _is_local_dep(locked):
            # LOCAL: liveness-only (§6.2.1). No hash compare.
            liveness_err = _verify_local_dep_liveness(name, dep_path)
            if liveness_err is not None:
                divergences.append(liveness_err)
            # No alias checks for local deps (local deps are not deduped into
            # CAS entries that multiple names could share).
            continue

        # --- four-state structural classification (§6.2.2) ---
        structural = _classify_dep_path(dep_path)
        if structural is not None:
            divergences.append(structural)
            continue

        # State (a) or plain dir/file: proceed to is_dir + identity check.
        if not dep_path.is_dir():
            divergences.append(
                f"{name}: expected directory at {dep_path}, found something else"
            )
            continue

        # State (a): attempt identity hash.  An OSError here is state (c).
        # A MilpaError (e.g. ID-NON-UTF8-RELPATH on a malformed entry) is also
        # caught and recorded as a divergence — matches Rust "cannot hash" branch
        # (lockfile.rs ~1050-1053).  Both paths continue the loop (no early abort).
        try:
            actual = compute_content_hash(dep_path)
        except OSError as exc:
            divergences.append(
                f"{name}: [{CAS_STORE_IO_ERROR}] I/O error reading store entry — {exc}"
            )
            continue
        except MilpaError as exc:
            divergences.append(
                f"{name}: cannot hash — {exc}"
            )
            continue

        expected = locked.identity
        if expected != actual:
            divergences.append(
                f"{name}: identity mismatch — "
                f"lockfile says {(expected or '<none>')[:23]}..., "
                f"actual {actual[:23]}..."
            )

        # --- §6.4 alias verification ---
        # canonical_target is the resolved (real) path of the store entry so we
        # can compare alias targets byte-for-byte.
        try:
            canonical_target = _os.path.realpath(dep_path)
        except OSError:
            canonical_target = None

        for alias in sorted(locked.aliases):
            alias_path = deps_dir / alias
            alias_is_link = alias_path.is_symlink()
            alias_exists = alias_path.exists()

            if not alias_is_link or not alias_exists:
                # Missing or dangling alias.
                divergences.append(
                    f"{alias}: [{VERIFY_ALIAS_SYMLINK_MISSING}] alias symlink "
                    f"absent or dangling for canonical '{name}'"
                )
                continue

            # Alias exists: verify it points at the same store entry.
            try:
                alias_target = _os.path.realpath(alias_path)
            except OSError:
                alias_target = None

            if canonical_target is None or alias_target != canonical_target:
                divergences.append(
                    f"{alias}: [{VERIFY_ALIAS_SYMLINK_MISSING}] alias symlink "
                    f"points to different store entry than canonical '{name}'"
                )

    # --- extra-dep scan (excludes hidden entries + declared alias names) ---
    # C1: namespace directories (``@<ns>/``) appear as top-level entries in
    # ``deps_dir/``.  Scan their children rather than flagging the namespace
    # dir itself as extra.
    if deps_dir.exists() and deps_dir.is_dir():
        for entry in sorted(deps_dir.iterdir()):
            if entry.name.startswith("."):
                continue
            if entry.name.startswith("@") and entry.is_dir():
                # Namespace directory: scan one level deeper.
                for child in sorted(entry.iterdir()):
                    qualified = f"{entry.name}/{child.name}"
                    if qualified not in expected_dir_names:
                        divergences.append(
                            f"{qualified}: extra dep in {deps_dir}/ not in lockfile"
                        )
            elif entry.name not in expected_dir_names:
                divergences.append(
                    f"{entry.name}: extra dep in {deps_dir}/ not in lockfile"
                )

    return divergences


