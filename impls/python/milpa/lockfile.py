# 4c — from_graph + format_lockfile (byte-exact hand-rolled templating)
# ---------------------------------------------------------------------------


def from_graph(graph: ResolvedGraph, *, strategy: str = "maxver") -> Lockfile:
    """Convert a ResolvedGraph into a Lockfile.

    Deps are sorted lexicographically by name (lockfile-schema.md §2.3 +
    §2.4 + resolver-semantics.md §4.4). Same graph always produces
    byte-identical lockfile text.
    """
    deps = tuple(
        sorted(
            (_locked_from_resolved(d) for d in graph.deps),
            key=lambda d: d.name,
        )
    )
    return Lockfile(deps=deps, strategy=strategy)


def _locked_from_resolved(d: ResolvedDep) -> LockedDep:
    """Translate a ResolvedDep into a LockedDep."""
    return LockedDep(
        name=d.name,
        identity=d.identity,
        version=d.version,
        src_dir=d.src_dir,
        # Sort lexicographically — requires is accumulated in BFS arrival order
        # which is non-deterministic across parallel-fetch runs. Lexicographic
        # order is the spec's single canonical ordering rule (§3.4 / §4.4).
        requires=tuple(sorted(d.requires)),
        provenances=(d.provenance,) if d.provenance is not None else (),
        active_flags=d.active_flags,
        self_mirrors=d.self_mirrors,
        # S6: carry the dep_decl hash from the resolver through to the lockfile pin.
        dep_decl=d.dep_decl,
    )


# ---------------------------------------------------------------------------
# _kdl_str — SSOT for string escaping (lockfile-schema.md §2.4)
#
# Escapes: \ → \\, " → \", control chars U+0000–U+001F → \u{NNNN},
# everything else verbatim. No named escapes (\n, \t, etc.) — the spec
# says "\u{NNNN}" for all control chars; for simplicity we use the unicode
# escape form for all U+0000–U+001F uniformly.
# ---------------------------------------------------------------------------

_CTRL_ESCAPES: dict[str, str] = {
    "\\": "\\\\",
    '"': '\\"',
}


def _kdl_str(s: str) -> str:
    r"""Return ``s`` as a double-quoted, KDL 2.0-escaped string literal.

    SSOT for string escaping in the lockfile emitter. Every string value
    emitted by ``format_lockfile`` passes through this function.

    Escape rules (lockfile-schema.md §2.4):
      \\  →  \\\\  (backslash escape)
      "   →  \\"   (double-quote escape)
      U+0000–U+001F → \u{NNNN}  (control chars in hex)
      everything else → verbatim (valid KDL 2.0 string content)
    """
    out: list[str] = []
    for ch in s:
        esc = _CTRL_ESCAPES.get(ch)
        if esc is not None:
            out.append(esc)
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def format_lockfile(lockfile: Lockfile) -> str:
    """Render a ``Lockfile`` to byte-exact KDL 2.0 text.

    Implements the canonical serialization rules from lockfile-schema.md §2.4.
    The output is deterministic: same logical lockfile → identical bytes.

    Layout:
      1. Header comment
      2. ``version 1`` (integer, unquoted)
      3. ``strategy "<name>"``
      4. Blank line
      5. dep blocks (lexicographic order), each followed by blank line
      6. File ends with the blank line after the last dep block (last byte = 0x0A)
    """
    lines: list[str] = [
        _HEADER,
        f"version {lockfile.version}",
        f"strategy {_kdl_str(lockfile.strategy)}",
        "",
    ]
    for dep in lockfile.deps:
        lines.append(f"dep {_kdl_str(dep.name)} {{")
        # identity — emitted only when not None
        if dep.identity is not None:
            lines.append(f"    identity {_kdl_str(dep.identity)}")
        lines.append(f"    version {_kdl_str(dep.version)}")
        lines.append(f"    src_dir {_kdl_str(dep.src_dir)}")
        # requires — always emitted; bare when empty, args when non-empty
        if dep.requires:
            req_args = " ".join(_kdl_str(r) for r in dep.requires)
            lines.append(f"    requires {req_args}")
        else:
            lines.append("    requires")
        # active_flags — omitted when empty
        if dep.active_flags:
            flag_args = " ".join(_kdl_str(f) for f in dep.active_flags)
            lines.append(f"    active_flags {flag_args}")
        # self_mirrors — omitted when empty; (url) annotation per §2.4
        if dep.self_mirrors:
            sm_args = " ".join(f"(url){_kdl_str(u)}" for u in dep.self_mirrors)
            lines.append(f"    self_mirrors {sm_args}")
        # dep_decl pin — S6: emitted only when present (forward-compat additive)
        if dep.dep_decl is not None:
            lines.append(f"    dep_decl {_kdl_str(dep.dep_decl)}")
        # provenance block
        for prov in dep.provenances:
            lines.append("    provenance {")
            for pline in _format_provenance_fields(prov):
                lines.append(f"        {pline}")
            lines.append("    }")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def _format_provenance_fields(p: ProvenanceRecord) -> list[str]:
    """Emit the kind discriminator + kind-specific fields for a provenance block.

    Field order per kind (lockfile-schema.md §2.4):
      git:      kind / url / ref / commit_sha
      tarball:  kind / url / sha256
      local:    kind / path
      member:   kind / name
      oci:      kind / registry / repository / digest
      registry: kind / name / tag / commit_sha  (read-compat; writer uses this too
                for any RegistryProvenanceRecord that may be round-tripped)

    Optional fields (ref, commit_sha, sha256, tag) are omitted when None.
    """
    out = [f"kind {_kdl_str(p.kind)}"]
    if isinstance(p, GitProvenanceRecord):
        out.append(f"url {_kdl_str(p.url)}")
        if p.ref is not None:
            out.append(f"ref {_kdl_str(p.ref)}")
        if p.commit_sha is not None:
            out.append(f"commit_sha {_kdl_str(p.commit_sha)}")
    elif isinstance(p, TarballProvenanceRecord):
        out.append(f"url {_kdl_str(p.url)}")
        if p.sha256 is not None:
            out.append(f"sha256 {_kdl_str(p.sha256)}")
    elif isinstance(p, LocalProvenanceRecord):
        out.append(f"path {_kdl_str(p.path)}")
    elif isinstance(p, MemberProvenanceRecord):
        out.append(f"name {_kdl_str(p.name)}")
    elif isinstance(p, OciProvenanceRecord):
        out.append(f"registry {_kdl_str(p.registry)}")
        out.append(f"repository {_kdl_str(p.repository)}")
        out.append(f"digest {_kdl_str(p.digest)}")
    elif isinstance(p, RegistryProvenanceRecord):
        out.append(f"name {_kdl_str(p.name)}")
        if p.tag is not None:
            out.append(f"tag {_kdl_str(p.tag)}")
        if p.commit_sha is not None:
            out.append(f"commit_sha {_kdl_str(p.commit_sha)}")
    return out


def write_lockfile(lockfile: Lockfile, path: Path) -> Path:
    """Write lockfile KDL text to ``path``. Returns the path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(format_lockfile(lockfile))
    return path


def load_lockfile(path: Path) -> Lockfile:
    """Read and parse a lockfile from disk.

    Raises ``MilpaError(LOCK_FILE_NOT_FOUND)`` / ``MilpaError(LOCK_FILE_UNREADABLE)``
    on I/O failure.
    """
    from milpa.errors import LOCK_FILE_NOT_FOUND, LOCK_FILE_UNREADABLE

    try:
        text = path.read_text()
    except FileNotFoundError as exc:
        raise MilpaError(
            LOCK_FILE_NOT_FOUND,
            f"lockfile not found: {path}",
            path=str(path),
        ) from exc
    except OSError as exc:
        raise MilpaError(
            LOCK_FILE_UNREADABLE,
            f"cannot read lockfile {path}: {exc}",
            path=str(path),
        ) from exc
    return parse_lockfile(text)


