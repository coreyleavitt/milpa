# 4b — parse_lockfile
# ---------------------------------------------------------------------------


def parse_lockfile(text: str) -> Lockfile:
    """Parse KDL 2.0 lockfile text into a ``Lockfile`` value.

    Raises ``MilpaError`` with LOCK-* slugs on any parse error.
    Defaults: strategy = "maxver" (tolerates pre-v1.0 lockfiles without the
    strategy node, per lockfile-schema.md §2.2).
    """
    doc = parse_kdl(text, context="lockfile")

    deps: list[LockedDep] = []
    strategy: str = "maxver"
    schema_version: int | None = None

    for node in nodes(doc):
        name = node_name(node)
        if name == "version":
            schema_version = _parse_top_version(node)
        elif name == "strategy":
            strategy = _parse_top_strategy(node)
        elif name == "dep":
            deps.append(_parse_dep(node))
        # Any other top-level node is silently ignored for forward compat

    if schema_version is None:
        raise MilpaError(
            LOCK_VERSION_MISSING,
            "lockfile missing required 'version' node",
        )
    if schema_version != LOCKFILE_SCHEMA_VERSION:
        raise MilpaError(
            LOCK_VERSION_UNSUPPORTED,
            f"unsupported lockfile schema version {schema_version} "
            f"(this milpa understands version {LOCKFILE_SCHEMA_VERSION})",
            got=schema_version,
            supported=LOCKFILE_SCHEMA_VERSION,
        )

    return Lockfile(deps=tuple(deps), strategy=strategy, version=schema_version)


def _parse_top_version(node: KdlNode) -> int:
    """Parse the top-level ``version`` node → schema version integer."""
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_FIELD_ARITY,
            f"'version' node takes exactly one argument, got {len(args)}",
        )
    val = args[0]
    as_int = value_as_int(val)
    if as_int is None:
        raise MilpaError(
            LOCK_FIELD_TYPE,
            f"'version' must be an integer, got {val!r}",
            got=val,
        )
    return as_int


def _parse_top_strategy(node: KdlNode) -> str:
    """Parse the top-level ``strategy`` node → strategy name string.

    The strategy node is optional (pre-v1.0 compat). If present and has
    exactly one string arg, use it. If present but malformed, we still
    default to "maxver" (fail-open for diagnostics — the strategy field is
    informational, not load-bearing for parse correctness).
    """
    args = node_args(node)
    if len(args) == 1:
        s = value_as_str(args[0])
        if s is not None:
            return s
    return "maxver"


def _parse_dep(node: KdlNode) -> LockedDep:
    """Parse a ``dep`` block into a ``LockedDep``."""
    dep_name = _require_dep_name(node)

    identity: str | None = None
    version: str = "0.0.0"
    src_dir: str = ""
    requires: tuple[str, ...] = ()
    active_flags: tuple[str, ...] = ()
    self_mirrors: tuple[str, ...] = ()
    provenances: list[ProvenanceRecord] = []
    dep_decl: str | None = None  # S6: additive dep_decl pin (§3.7)

    for child in node_children(node):
        cname = node_name(child)
        if cname == "identity":
            identity = _parse_dep_identity(child, dep_name)
        elif cname == "version":
            version = _parse_dep_scalar_str(child, dep_name, "version")
        elif cname == "src_dir":
            src_dir = _parse_dep_scalar_str(child, dep_name, "src_dir")
        elif cname == "requires":
            requires = _parse_dep_requires(child)
        elif cname == "active_flags":
            active_flags = _parse_dep_active_flags(child)
        elif cname == "self_mirrors":
            self_mirrors = _parse_dep_self_mirrors(child)
        elif cname == "provenance":
            provenances.append(_parse_provenance_block(child, dep_name))
        elif cname == "dep_decl":
            # S6: forward-compat parse — silently ignored when absent or malformed.
            args = node_args(child)
            if len(args) == 1:
                dep_decl = value_as_str(args[0])
        # other unknown child nodes are silently skipped (forward compat)

    return LockedDep(
        name=dep_name,
        identity=identity,
        version=version,
        src_dir=src_dir,
        requires=requires,
        provenances=tuple(provenances),
        active_flags=active_flags,
        self_mirrors=self_mirrors,
        dep_decl=dep_decl,
    )


def _require_dep_name(node: KdlNode) -> str:
    """Extract the dep name from the positional arg of a ``dep`` node."""
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_DEP_NAME_ARITY,
            f"dep node requires exactly one string argument (the name), "
            f"got {len(args)} args",
        )
    name = value_as_str(args[0])
    if name is None:
        raise MilpaError(
            LOCK_DEP_NAME_ARITY,
            f"dep node name argument must be a string, got {args[0]!r}",
        )
    return name


def _parse_dep_identity(node: KdlNode, dep_name: str) -> str:
    """Parse the ``identity`` child of a dep block."""
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_DEP_FIELD_ARITY,
            f"dep {dep_name!r}: 'identity' must have exactly one string value",
            dep=dep_name,
        )
    val = args[0]
    # Validate multihash format (lockfile-schema.md §3.1)
    return _parse_identity_for_lockfile(val, dep_name)


def _parse_dep_scalar_str(node: KdlNode, dep_name: str, field: str) -> str:
    """Parse a dep child node that takes exactly one string arg."""
    args = node_args(node)
    if len(args) != 1:
        raise MilpaError(
            LOCK_DEP_FIELD_ARITY,
            f"dep {dep_name!r}: {field!r} must have exactly one string value, "
            f"got {len(args)} args",
            dep=dep_name,
            field=field,
        )
    s = value_as_str(args[0])
    if s is None:
        raise MilpaError(
            LOCK_DEP_FIELD_ARITY,
            f"dep {dep_name!r}: {field!r} value must be a string, got {args[0]!r}",
            dep=dep_name,
            field=field,
        )
    return s


def _parse_dep_requires(node: KdlNode) -> tuple[str, ...]:
    """Parse the ``requires`` child node — zero or more string args."""
    return tuple(s for a in node_args(node) if (s := value_as_str(a)) is not None)


def _parse_dep_active_flags(node: KdlNode) -> tuple[str, ...]:
    """Parse the ``active_flags`` child node — zero or more string args."""
    return tuple(s for a in node_args(node) if (s := value_as_str(a)) is not None)


def _parse_dep_self_mirrors(node: KdlNode) -> tuple[str, ...]:
    """Parse the ``self_mirrors`` child node.

    Accepts both plain strings and (url)-annotated values. The raw kdl-py
    entry value must be accessed to detect the url tag. We use node_args
    which strips annotations — both forms return a str through value_as_str.
    """
    return tuple(s for a in node_args(node) if (s := value_as_str(a)) is not None)


def _parse_provenance_block(node: KdlNode, dep_name: str) -> ProvenanceRecord:
    """Parse a ``provenance { ... }`` block into a ProvenanceRecord."""
    # Collect all scalar child fields into a dict
    fields: dict[str, str] = {}
    for child in node_children(node):
        cname = node_name(child)
        child_args = node_args(child)
        if len(child_args) != 1:
            raise MilpaError(
                LOCK_PROV_FIELD_ARITY,
                f"dep {dep_name!r}: provenance field {cname!r} must have "
                f"exactly one value, got {len(child_args)}",
                dep=dep_name,
                field=cname,
            )
        raw = child_args[0]
        s = value_as_str(raw)
        if s is None:
            raise MilpaError(
                LOCK_PROV_FIELD_ARITY,
                f"dep {dep_name!r}: provenance field {cname!r} must be a "
                f"string, got {raw!r}",
                dep=dep_name,
                field=cname,
            )
        fields[cname] = s

    # kind discriminator is required
    kind = fields.get("kind")
    if kind is None:
        raise MilpaError(
            LOCK_PROV_KIND_MISSING,
            f"dep {dep_name!r}: provenance block missing 'kind' discriminator",
            dep=dep_name,
        )

    if kind == "git":
        return GitProvenanceRecord(
            url=_req_field(fields, "url", dep_name),
            ref=fields.get("ref"),
            commit_sha=fields.get("commit_sha"),
        )
    if kind == "tarball":
        return TarballProvenanceRecord(
            url=_req_field(fields, "url", dep_name),
            sha256=fields.get("sha256"),
        )
    if kind == "local":
        return LocalProvenanceRecord(
            path=_req_field(fields, "path", dep_name),
        )
    if kind == "member":
        return MemberProvenanceRecord(
            name=_req_field(fields, "name", dep_name),
        )
    if kind == "oci":
        return OciProvenanceRecord(
            registry=_req_field(fields, "registry", dep_name),
            repository=_req_field(fields, "repository", dep_name),
            digest=_req_field(fields, "digest", dep_name),
        )
    if kind == "registry":
        # Read-compat only (§4.6); writer never emits this
        return RegistryProvenanceRecord(
            name=_req_field(fields, "name", dep_name),
            tag=fields.get("tag"),
            commit_sha=fields.get("commit_sha"),
        )

    raise MilpaError(
        LOCK_PROV_KIND_UNKNOWN,
        f"dep {dep_name!r}: unknown provenance kind {kind!r} "
        f"(known: git, tarball, local, member, oci, registry)",
        dep=dep_name,
        kind=kind,
    )


def _req_field(fields: dict[str, str], key: str, dep_name: str) -> str:
    """Return a required provenance field, raising LOCK-PROV-FIELD-MISSING if absent."""
    val = fields.get(key)
    if val is None:
        raise MilpaError(
            LOCK_PROV_FIELD_MISSING,
            f"dep {dep_name!r}: provenance missing required field {key!r}",
            dep=dep_name,
            field=key,
        )
    return val


