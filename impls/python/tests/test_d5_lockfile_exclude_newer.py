class TestNoSilentDropUpdateRemove:
    def test_update_carries_forward_exclude_newer(self, tmp_path: Path) -> None:
        project_dir, mocked_dir = _setup_project(tmp_path)
        rc, _out, err = _run_main(
            ["-C", str(project_dir), "fetch", "--exclude-newer", "2026-01-01T00:00:00Z"],
            mocked_dir,
            project_dir,
        )
        assert rc == 0, f"fetch must succeed; stderr={err!r}"
        lock = load_lockfile(project_dir / "milpa.lock")
        assert lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z")

        # Bare `update` — no CLI flag, manifest has no resolution{} block.
        rc, _out, err = _run_main(
            ["-C", str(project_dir), "update"], mocked_dir, project_dir
        )
        assert rc == 0, f"update must succeed; stderr={err!r}"
        new_lock = load_lockfile(project_dir / "milpa.lock")
        assert new_lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z"), (
            "bare `update` must carry forward the prior lock's exclude_newer, not drop it"
        )

    def test_remove_carries_forward_exclude_newer(self, tmp_path: Path) -> None:
        project_dir = tmp_path / "project"
        project_dir.mkdir()
        (project_dir / "milpa.kdl").write_text(
            'name "myapp"\nkind "application"\ndeps {\n'
            '    foo git=(url)"https://example.com/foo.git" ref="v1.0.0"\n'
            '    bar git=(url)"https://example.com/bar.git" ref="v1.0.0"\n'
            "}\n",
            encoding="utf-8",
        )
        mocked_dir = tmp_path / "mocked-fetches"
        mocked_dir.mkdir()
        _make_git_mock(
            mocked_dir, "https://example.com/foo.git", "v1.0.0", sha="a" * 40, marker="foo"
        )
        _make_git_mock(
            mocked_dir, "https://example.com/bar.git", "v1.0.0", sha="b" * 40, marker="bar"
        )

        rc, _out, err = _run_main(
            ["-C", str(project_dir), "fetch", "--exclude-newer", "2026-01-01T00:00:00Z"],
            mocked_dir,
            project_dir,
        )
        assert rc == 0, f"fetch must succeed; stderr={err!r}"
        lock = load_lockfile(project_dir / "milpa.lock")
        assert lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z")

        rc, _out, err = _run_main(
            ["-C", str(project_dir), "remove", "bar"], mocked_dir, project_dir
        )
        assert rc == 0, f"remove must succeed; stderr={err!r}"
        new_lock = load_lockfile(project_dir / "milpa.lock")
        assert new_lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z"), (
            "single-package `remove` must carry forward the prior lock's exclude_newer"
        )


class TestLockedFlagsDroppedExcludeNewerAsDrift:
    def test_locked_flags_dropped_exclude_newer(self, tmp_path: Path) -> None:
        project_dir, mocked_dir = _setup_project(tmp_path)
        rc, _out, err = _run_main(
            ["-C", str(project_dir), "fetch", "--exclude-newer", "2026-01-01T00:00:00Z"],
            mocked_dir,
            project_dir,
        )
        assert rc == 0, f"fetch must succeed; stderr={err!r}"
        lock = load_lockfile(project_dir / "milpa.lock")
        assert lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z")

        # `--locked` this time WITHOUT --exclude-newer: the manifest has no
        # resolution{} block either, so the effective (2-tier, fetch/lock-
        # scoped) value is None — a real drop from the committed lock.
        rc, _out, err = _run_main(
            ["-C", str(project_dir), "fetch", "--locked"], mocked_dir, project_dir
        )
        assert rc == 1
        assert "RES-LOCKED-DRIFT" in err

    def test_locked_passes_when_exclude_newer_unchanged(self, tmp_path: Path) -> None:
        project_dir, mocked_dir = _setup_project(tmp_path)
        rc, _out, err = _run_main(
            ["-C", str(project_dir), "fetch", "--exclude-newer", "2026-01-01T00:00:00Z"],
            mocked_dir,
            project_dir,
        )
        assert rc == 0, f"fetch must succeed; stderr={err!r}"

        rc, _out, err = _run_main(
            [
                "-C", str(project_dir), "fetch", "--locked",
                "--exclude-newer", "2026-01-01T00:00:00Z",
            ],
            mocked_dir,
            project_dir,
        )
        assert rc == 0, f"--locked with an unchanged exclude_newer must pass; stderr={err!r}"
