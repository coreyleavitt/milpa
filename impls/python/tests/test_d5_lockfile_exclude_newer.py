class TestLockfileExcludeNewerRoundTrip:
    def test_absent_by_default(self) -> None:
        lock = parse_lockfile("version 1\nstrategy \"maxver\"\n")
        assert lock.exclude_newer is None

    def test_parses_present_node(self) -> None:
        lock = parse_lockfile(
            'version 1\nstrategy "maxver"\nexclude_newer "2026-01-01T00:00:00Z"\n'
        )
        assert lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z")

    def test_omitted_from_emission_when_absent(self) -> None:
        lock = Lockfile(deps=(), strategy="maxver", exclude_newer=None)
        text = format_lockfile(lock)
        assert "exclude_newer" not in text

    def test_emitted_right_after_strategy_when_present(self) -> None:
        lock = Lockfile(deps=(), strategy="maxver", exclude_newer=_TS)
        text = format_lockfile(lock)
        assert text == (
            "// generated by milpa; reproducible build snapshot\n"
            "version 1\n"
            'strategy "maxver"\n'
            'exclude_newer "2026-01-01T00:00:00Z"\n'
        )

    def test_round_trips_through_format_and_parse(self) -> None:
        lock = Lockfile(deps=(), strategy="maxver", exclude_newer=_TS)
        text = format_lockfile(lock)
        reparsed = parse_lockfile(text)
        assert reparsed.exclude_newer == _TS

    def test_from_graph_carries_exclude_newer_through(self) -> None:
        graph = ResolvedGraph(deps=())
        lock = from_graph(graph, strategy="maxver", exclude_newer=_TS)
        assert lock.exclude_newer == _TS
        lock_none = from_graph(graph, strategy="maxver")
        assert lock_none.exclude_newer is None

    def test_malformed_arity_raises_lock_field_arity(self) -> None:
        from milpa.errors import MilpaError

        try:
            parse_lockfile('version 1\nstrategy "maxver"\nexclude_newer "a" "b"\n')
            assert False, "expected LOCK-FIELD-ARITY"
        except MilpaError as e:
            assert e.slug == "LOCK-FIELD-ARITY"

    def test_malformed_type_raises_lock_field_type(self) -> None:
        from milpa.errors import MilpaError

        try:
            parse_lockfile('version 1\nstrategy "maxver"\nexclude_newer 42\n')
            assert False, "expected LOCK-FIELD-TYPE"
        except MilpaError as e:
            assert e.slug == "LOCK-FIELD-TYPE"

    def test_unparseable_timestamp_raises_lock_field_type(self) -> None:
        from milpa.errors import MilpaError

        try:
            parse_lockfile('version 1\nstrategy "maxver"\nexclude_newer "not-a-date"\n')
            assert False, "expected LOCK-FIELD-TYPE"
        except MilpaError as e:
            assert e.slug == "LOCK-FIELD-TYPE"


