def _make_workspace_with_resolution(
    tmp_path: Path, *, resolution_block: str = ""
) -> "object":
    from milpa.workspace import load_workspace

    root_dir = tmp_path / "project"
    root_dir.mkdir()
    (root_dir / "milpa.kdl").write_text(
        'workspace {\n    member "mylib"\n}\n' f"{resolution_block}",
        encoding="utf-8",
    )
    lib_dir = root_dir / "mylib"
    lib_dir.mkdir()
    (lib_dir / "milpa.kdl").write_text(
        'name "mylib"\nkind "library"\n', encoding="utf-8"
    )
    return load_workspace(root_dir), lib_dir


class TestWorkspaceFrozenBaselineFollowsRootExcludeNewer:
    def test_workspace_frozen_passes_with_matching_root_and_lock(
        self, tmp_path: Path
    ) -> None:
        from milpa.cas import CAStore
        from milpa.context import MilpaEnv
        from milpa.identity import compute_content_hash
        from milpa.lockfile import LockedDep, MemberProvenanceRecord
        from milpa.frozen import resolve_workspace_frozen

        workspace, lib_dir = _make_workspace_with_resolution(
            tmp_path,
            resolution_block='resolution {\n    exclude-newer "2026-01-01T00:00:00Z"\n}\n',
        )
        member_identity = compute_content_hash(lib_dir)
        member_locked = LockedDep(
            name="mylib",
            identity=member_identity,
            version="0.0.1",
            src_dir="",
            requires=(),
            provenances=(MemberProvenanceRecord(name="mylib"),),
            aliases=(),
        )
        lockfile = Lockfile(
            deps=(member_locked,),
            strategy="maxver",
            exclude_newer=_parse_timestamp("2026-01-01T00:00:00Z"),
        )

        cas_root = tmp_path / ".cas"
        cas_root.mkdir()
        env = MilpaEnv(fetcher=None, index=None, store=CAStore(cas_root))  # type: ignore[arg-type]
        deps_dir = tmp_path / "_deps"

        graph = resolve_workspace_frozen(workspace, lockfile, env, deps_dir)
        assert graph is not None

    def test_workspace_frozen_fails_on_genuine_root_divergence(
        self, tmp_path: Path
    ) -> None:
        from milpa.cas import CAStore
        from milpa.context import MilpaEnv
        from milpa.errors import FROZEN_EXCLUDE_NEWER_MISMATCH, MilpaError
        from milpa.identity import compute_content_hash
        from milpa.lockfile import LockedDep, MemberProvenanceRecord
        from milpa.frozen import resolve_workspace_frozen

        workspace, lib_dir = _make_workspace_with_resolution(
            tmp_path,
            resolution_block='resolution {\n    exclude-newer "2026-01-01T00:00:00Z"\n}\n',
        )
        member_identity = compute_content_hash(lib_dir)
        member_locked = LockedDep(
            name="mylib",
            identity=member_identity,
            version="0.0.1",
            src_dir="",
            requires=(),
            provenances=(MemberProvenanceRecord(name="mylib"),),
            aliases=(),
        )
        lockfile = Lockfile(
            deps=(member_locked,),
            strategy="maxver",
            exclude_newer=_parse_timestamp("2020-01-01T00:00:00Z"),
        )

        cas_root = tmp_path / ".cas"
        cas_root.mkdir()
        env = MilpaEnv(fetcher=None, index=None, store=CAStore(cas_root))  # type: ignore[arg-type]
        deps_dir = tmp_path / "_deps"

        try:
            resolve_workspace_frozen(workspace, lockfile, env, deps_dir)
            assert False, "expected FROZEN-EXCLUDE-NEWER-MISMATCH"
        except MilpaError as e:
            assert e.slug == FROZEN_EXCLUDE_NEWER_MISMATCH


