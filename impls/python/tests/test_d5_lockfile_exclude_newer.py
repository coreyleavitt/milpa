class TestFrozenBaselineFollowsManifestExcludeNewer:
    def test_frozen_passes_with_matching_manifest_and_lock(self, tmp_path: Path) -> None:
        project_dir, mocked_dir = _setup_project(
            tmp_path,
            resolution_block='resolution {\n    exclude-newer "2026-01-01T00:00:00Z"\n}\n',
        )
        rc, _out, err = _run_main(
            ["-C", str(project_dir), "fetch", "--exclude-newer", "2026-01-01T00:00:00Z"],
            mocked_dir,
            project_dir,
        )
        assert rc == 0, f"fetch must succeed; stderr={err!r}"
        lock = load_lockfile(project_dir / "milpa.lock")
        assert lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z")

        rc, _out, err = _run_main(
            ["-C", str(project_dir), "--frozen", "fetch"], mocked_dir, project_dir
        )
        assert rc == 0, (
            f"frozen fetch must succeed on a genuinely-consistent exclude-newer lock; "
            f"stderr={err!r}"
        )
        assert "milpa-error:" not in err

    def test_frozen_default_baseline_unchanged_with_no_resolution_block(
        self, tmp_path: Path
    ) -> None:
        project_dir, mocked_dir = _setup_project(tmp_path)
        rc, _out, _err = _run_main(
            ["-C", str(project_dir), "fetch"], mocked_dir, project_dir
        )
        assert rc == 0
        lock = load_lockfile(project_dir / "milpa.lock")
        assert lock.exclude_newer is None

        rc, _out, err = _run_main(
            ["-C", str(project_dir), "--frozen", "fetch"], mocked_dir, project_dir
        )
        assert rc == 0, f"frozen fetch must succeed with no recorded exclude_newer; stderr={err!r}"


class TestFrozenStillCatchesGenuineExcludeNewerDivergence:
    def test_frozen_fails_when_manifest_exclude_newer_changes_after_lock(
        self, tmp_path: Path
    ) -> None:
        project_dir, mocked_dir = _setup_project(
            tmp_path,
            resolution_block='resolution {\n    exclude-newer "2026-01-01T00:00:00Z"\n}\n',
        )
        rc, _out, _err = _run_main(
            ["-C", str(project_dir), "fetch", "--exclude-newer", "2026-01-01T00:00:00Z"],
            mocked_dir,
            project_dir,
        )
        assert rc == 0
        lock = load_lockfile(project_dir / "milpa.lock")
        assert lock.exclude_newer == _parse_timestamp("2026-01-01T00:00:00Z")

        # Mutate the manifest's declared exclude-newer WITHOUT re-resolving.
        (project_dir / "milpa.kdl").write_text(
            _manifest_kdl(
                resolution_block='resolution {\n    exclude-newer "2020-01-01T00:00:00Z"\n}\n'
            ),
            encoding="utf-8",
        )

        rc, _out, err = _run_main(
            ["-C", str(project_dir), "--frozen", "fetch"], mocked_dir, project_dir
        )
        assert rc == 1
        assert "FROZEN-EXCLUDE-NEWER-MISMATCH" in err

    def test_frozen_fails_when_manifest_adds_exclude_newer_lock_has_none(
        self, tmp_path: Path
    ) -> None:
        project_dir, mocked_dir = _setup_project(tmp_path)
        rc, _out, _err = _run_main(
            ["-C", str(project_dir), "fetch"], mocked_dir, project_dir
        )
        assert rc == 0
        lock = load_lockfile(project_dir / "milpa.lock")
        assert lock.exclude_newer is None

        (project_dir / "milpa.kdl").write_text(
            _manifest_kdl(
                resolution_block='resolution {\n    exclude-newer "2026-01-01T00:00:00Z"\n}\n'
            ),
            encoding="utf-8",
        )

        rc, _out, err = _run_main(
            ["-C", str(project_dir), "--frozen", "fetch"], mocked_dir, project_dir
        )
        assert rc == 1
        assert "FROZEN-EXCLUDE-NEWER-MISMATCH" in err


