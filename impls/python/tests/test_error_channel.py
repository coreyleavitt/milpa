"""The machine-readable error channel — Gap-1 (RFC differential-
conformance-harness) R1–R4.

On any diagnosed failure the CLI MUST emit exactly one terminal
`milpa-error: <SLUG>` line to stderr; an exit-0 run MUST NOT emit one;
an exception escaping the typed handlers routes to the MILPA-INTERNAL
sentinel; argument-parse failures exit 2 (a usage/crash-class verdict
with no `milpa-error:` line).

These drive the CLI through its public entry point `main(argv)` and
read the slug off captured stderr — the same channel a language-neutral
black-box runner observes (cli-contract.md §3.1).
"""

import re

import pytest

from milpa.cli import main

_SLUG_LINE = re.compile(r"^milpa-error: ([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+)$", re.M)


def _slug_lines(stderr: str) -> list[str]:
    """Return every full-line `milpa-error: <SLUG>` match's slug."""
    return _SLUG_LINE.findall(stderr)


def test_manifest_syntax_error_emits_terminal_slug_line(tmp_path, capsys):
    """`fetch` over a malformed milpa.kdl exits 1 with exactly one
    `milpa-error: MAN-KDL-SYNTAX` line (the R1/R2 channel)."""
    (tmp_path / "milpa.kdl").write_text('name "x"\ndeps {\n')  # unbalanced

    rc = main(["-C", str(tmp_path), "fetch"])

    assert rc == 1
    err = capsys.readouterr().err
    assert _slug_lines(err) == ["MAN-KDL-SYNTAX"]


def test_successful_run_emits_no_slug_line(tmp_path, capsys):
    """R3: an exit-0 run MUST NOT emit a `milpa-error:` line."""
    rc = main(["-C", str(tmp_path), "clean"])  # idempotent, exits 0

    assert rc == 0
    assert _slug_lines(capsys.readouterr().err) == []


def test_show_without_lockfile_emits_lock_file_not_found(tmp_path, capsys):
    """A missing lockfile is a diagnosed condition, not an internal error:
    `show` exits 1 with the LOCK-FILE-NOT-FOUND slug."""
    rc = main(["-C", str(tmp_path), "show"])

    assert rc == 1
    assert _slug_lines(capsys.readouterr().err) == ["LOCK-FILE-NOT-FOUND"]


def test_unexpected_exception_routes_to_internal_sentinel(
    tmp_path, capsys, monkeypatch
):
    """R3 net: an exception with no `.code` escaping a verb is rendered
    as the MILPA-INTERNAL sentinel and exits 1 (not a silent crash)."""
    def boom(*a, **k):
        raise RuntimeError("unexpected")

    monkeypatch.setattr("milpa.cli.cmd_show", boom)
    rc = main(["-C", str(tmp_path), "show"])

    assert rc == 1
    assert _slug_lines(capsys.readouterr().err) == ["MILPA-INTERNAL"]


def test_argument_parse_error_exits_2_with_no_slug_line(tmp_path, capsys):
    """R4: an argument-parse / usage error exits 2 (crash-class verdict)
    and emits NO `milpa-error:` line."""
    with pytest.raises(SystemExit) as exc:
        main(["-s", "bogus", "-C", str(tmp_path), "fetch"])

    assert exc.value.code == 2
    assert _slug_lines(capsys.readouterr().err) == []


def test_malformed_named_dep_constraint_emits_man_dep_named_constraint(
    tmp_path, capsys
):
    """A syntactically invalid NamedDep constraint must surface as
    MAN-DEP-NAMED-CONSTRAINT (not MILPA-INTERNAL) through the CLI.

    This is the black-box signal: the parse-boundary validation is in
    effect when the manifest is loaded, before any resolve-time code
    runs. Regression guard against the old behaviour where ValueError
    from VersionSet.from_constraint escaped to the MILPA-INTERNAL
    catch-all."""
    (tmp_path / "milpa.kdl").write_text(
        'name "x"\ndeps {\n    z "@@@bad"\n}\n'
    )

    rc = main(["-C", str(tmp_path), "fetch"])

    assert rc == 1
    err = capsys.readouterr().err
    assert _slug_lines(err) == ["MAN-DEP-NAMED-CONSTRAINT"]


