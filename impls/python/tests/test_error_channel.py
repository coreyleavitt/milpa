def test_workspace_with_kind_emits_workspace_has_deps_or_kind(tmp_path, capsys):
    """A workspace manifest that also declares `kind` must emit
    MAN-WORKSPACE-HAS-DEPS-OR-KIND, not be silently swallowed into a
    generic "no manifest" path (bug #119 regression).

    Previously `find_workspace_root` swallowed the ManifestError from
    `parse_workspace_or_manifest`, so the CLI fell through to the package
    parse path and emitted the wrong slug (or crashed).
    """
    (tmp_path / "milpa.kdl").write_text(
        'name "x"\n'
        'kind "library"\n'
        'workspace {\n'
        '    member "a"\n'
        '}\n'
    )
    rc = main(["-C", str(tmp_path), "fetch"])
    assert rc == 1
    assert _slug_lines(capsys.readouterr().err) == ["MAN-WORKSPACE-HAS-DEPS-OR-KIND"]


