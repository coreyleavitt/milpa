def _make_resolved_dep(
    name: str = "foo",
    *,
    identity: str | None = _VALID_IDENTITY,
    version: str = "0.0.1",
    src_dir: str = "",
    requires: tuple[str, ...] = (),
    provenance: object = None,
    active_flags: tuple[str, ...] = (),
) -> ResolvedDep:
    # D-lifecycle: ResolvedDep.provenance (singular) → provenances (plural).
    # Wrap the single provenance in a tuple, or use empty tuple for None.
    from milpa.lockfile import ProvenanceRecord as _PR
    provs: tuple[_PR, ...] = (provenance,) if isinstance(provenance, _PR) else ()  # type: ignore[assignment]
    return ResolvedDep(
        name=name,
        identity=identity,
        version=version,
        src_dir=src_dir,
        requires=requires,
        provenances=provs,
        active_flags=active_flags,
    )


