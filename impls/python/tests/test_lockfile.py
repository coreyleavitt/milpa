    def test_store_io_error_classified_correctly(self, tmp_path: Path) -> None:
        """State (c): symlink resolves but reading the store entry raises → CAS-STORE-IO-ERROR.

        We trigger a GENUINE I/O error (no mocking, per the project rule): a
        chmod-000 regular FILE inside the store entry.  The directory listing
        in compute_content_hash's rglob succeeds, but read_bytes() on the
        unreadable file raises PermissionError — the same OSError class as a
        network mount going offline mid-read.  verify_lockfile_against_deps
        must classify it as CAS-STORE-IO-ERROR, not content-mismatch or dangling.
        """
        if os.geteuid() == 0:
            pytest.skip("chmod-based I/O error test is a no-op as root")

        deps_dir = tmp_path / "_deps"
        deps_dir.mkdir()
        store_entry = _make_store_entry(tmp_path, "foo-store")
        unreadable = store_entry / "lib.nim"
        (deps_dir / "foo").symlink_to(store_entry)

        dep = _make_locked_dep("foo")
        lf = Lockfile(deps=(dep,))

        os.chmod(unreadable, 0o000)
        try:
            result = verify_lockfile_against_deps(lf, deps_dir)
        finally:
            # Restore the mode so the tmp tree can be cleaned up.
            os.chmod(unreadable, 0o644)

        assert len(result) == 1, f"expected 1 divergence, got {result}"
        assert "foo" in result[0]
        assert "CAS-STORE-IO-ERROR" in result[0]
        assert "dangling" not in result[0]
        assert not result[0].startswith("foo: missing")

