_sha256_st = st.just("a" * 64)
_version_st = st.from_regex(r"[0-9]+\.[0-9]+\.[0-9]+", fullmatch=True)
_url_st = st.just("https://example.com/foo.git")
_src_dir_st = st.one_of(st.just(""), st.just("src"), st.just("lib"))


def _make_simple_lockfile(deps: list[tuple[str, str, str, str]]) -> str:
    """Build a minimal lockfile text with git deps."""
    lines = [
        "// generated by milpa; reproducible build snapshot",
        "version 1",
        'strategy "maxver"',
        "",
    ]
    for name, version, src_dir, identity in deps:
        lines.append(f'dep "{name}" {{')
        lines.append(f'    identity "sha256:{identity}"')
        lines.append(f'    version "{version}"')
        lines.append(f'    src_dir "{src_dir}"')
        lines.append("    requires")
        lines.append("    provenance {")
        lines.append('        origin "observed"')
        lines.append('        kind "git"')
        lines.append('        url "https://example.com/foo.git"')
        lines.append("    }")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


