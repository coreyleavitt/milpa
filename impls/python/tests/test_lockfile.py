def _make_resolved_dep(
    name: str = "foo",
    *,
    identity: str | None = _VALID_IDENTITY,
    version: str = "0.0.1",
    src_dir: str = "",
    requires: tuple[str, ...] = (),
    provenance: object = None,
    active_flags: tuple[str, ...] = (),
    self_mirrors: tuple[str, ...] = (),
) -> ResolvedDep:
    return ResolvedDep(
        name=name,
        identity=identity,
        version=version,
        src_dir=src_dir,
        requires=requires,
        provenance=provenance,  # type: ignore[arg-type]
        active_flags=active_flags,
        self_mirrors=self_mirrors,
    )


