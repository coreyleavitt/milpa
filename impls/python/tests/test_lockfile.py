# Strategies for Hypothesis
_safe_str = st.text(
    alphabet=st.characters(
        whitelist_categories=("Lu", "Ll", "Nd"),
        whitelist_characters="/_-.@",
    ),
    min_size=1,
    max_size=20,
)
_dep_name_st = st.from_regex(r"[a-z][a-z0-9_-]{0,15}", fullmatch=True)
_sha256_st = st.just("a" * 64)
_version_st = st.from_regex(r"[0-9]+\.[0-9]+\.[0-9]+", fullmatch=True)
_url_st = st.just("https://example.com/foo.git")
_src_dir_st = st.one_of(st.just(""), st.just("src"), st.just("lib"))


def _make_simple_lockfile(deps: list[tuple[str, str, str, str]]) -> str:
    """Build a minimal lockfile text with git deps."""
    lines = [
        "// generated by milpa; reproducible build snapshot",
        "version 1",
        'strategy "maxver"',
        "",
    ]
    for name, version, src_dir, identity in deps:
        lines.append(f'dep "{name}" {{')
        lines.append(f'    identity "sha256:{identity}"')
        lines.append(f'    version "{version}"')
        lines.append(f'    src_dir "{src_dir}"')
        lines.append("    requires")
        lines.append("    provenance {")
        lines.append('        kind "git"')
        lines.append('        url "https://example.com/foo.git"')
        lines.append("    }")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


@given(
    name=_dep_name_st,
    version=_version_st,
    src_dir=_src_dir_st,
    sha=_sha256_st,
)
@settings(max_examples=50)
def test_parse_roundtrip_single_git_dep(
    name: str,
    version: str,
    src_dir: str,
    sha: str,
) -> None:
    """A lockfile with a single git dep parses correctly."""
    text = _make_simple_lockfile([(name, version, src_dir, sha)])
    lf = parse_lockfile(text)
    assert len(lf.deps) == 1
    dep = lf.deps[0]
    assert dep.name == name
    assert dep.version == version
    assert dep.src_dir == src_dir
    assert dep.identity == f"sha256:{sha}"


@given(
    names=st.lists(
        _dep_name_st, min_size=1, max_size=5, unique=True
    ),
)
@settings(max_examples=30)
def test_parse_multiple_deps_returns_all(names: list[str]) -> None:
    """Multiple dep blocks all parse."""
    text = _make_simple_lockfile([(n, "1.0.0", "", "a" * 64) for n in names])
    lf = parse_lockfile(text)
    assert len(lf.deps) == len(names)
    parsed_names = {d.name for d in lf.deps}
    assert parsed_names == set(names)


