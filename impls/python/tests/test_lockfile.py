    def test_milpa_error_from_hash_recorded_as_divergence_loop_continues(
        self, tmp_path: Path
    ) -> None:
        """MilpaError from compute_content_hash is recorded, NOT raised; loop continues.

        Regression test for Fix 1 (R1-10): previously the MilpaError escaped the
        try/except and aborted verify early.  Now it must be caught, converted to
        a "cannot hash" divergence string, and the next dep must still be checked.

        Trigger: a dep directory containing a file with non-UTF-8 bytes in its
        name causes compute_content_hash to raise MilpaError(ID-NON-UTF8-RELPATH).
        A SECOND dep (with a normal name) must also be reported (missing), proving
        that the loop was NOT aborted by the MilpaError from the first dep.

        Uses real filesystem I/O (os.open with raw bytes) — no mocking.
        """
        import os as _os

        deps_dir = tmp_path / "_deps"
        deps_dir.mkdir()

        # Dep "bad": a real directory containing a file with a non-UTF-8 filename.
        # This forces compute_content_hash to raise MilpaError(ID-NON-UTF8-RELPATH).
        bad_dir = deps_dir / "bad"
        bad_dir.mkdir()
        bad_filename = b"file_\xff_name"  # 0xff is not valid UTF-8
        bad_file_bytes = bad_dir.as_posix().encode() + b"/" + bad_filename
        fd = _os.open(bad_file_bytes, _os.O_CREAT | _os.O_WRONLY, 0o644)
        _os.write(fd, b"content")
        _os.close(fd)

        # Dep "other": genuinely missing (no entry at deps_dir/other).
        # This dep should ALSO be reported — proving the loop was not aborted.

        dep_bad = _make_locked_dep("bad")
        dep_other = _make_locked_dep("other")
        lf = Lockfile(deps=(dep_bad, dep_other))
        result = verify_lockfile_against_deps(lf, deps_dir)

        # Both deps must produce divergences.
        assert len(result) == 2, (
            f"expected exactly 2 divergences (bad + other), got {result!r}"
        )

        bad_divs = [r for r in result if r.startswith("bad:")]
        other_divs = [r for r in result if r.startswith("other:")]

        assert len(bad_divs) == 1, f"expected 1 divergence for 'bad', got {bad_divs}"
        assert "cannot hash" in bad_divs[0], (
            f"'bad' divergence must contain 'cannot hash', got {bad_divs[0]!r}"
        )

        assert len(other_divs) == 1, f"expected 1 divergence for 'other', got {other_divs}"
        assert "missing" in other_divs[0], (
            f"'other' divergence must contain 'missing', got {other_divs[0]!r}"
        )


