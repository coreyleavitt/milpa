class TestKdlStr:
    def test_simple_string(self) -> None:
        assert _kdl_str("hello") == '"hello"'

    def test_escapes_backslash(self) -> None:
        assert _kdl_str("a\\b") == '"a\\\\b"'

    def test_escapes_double_quote(self) -> None:
        assert _kdl_str('a"b') == '"a\\"b"'

    def test_escapes_both(self) -> None:
        assert _kdl_str('v1"x\\y') == '"v1\\"x\\\\y"'

    def test_escapes_control_chars(self) -> None:
        # U+0000 → \u{0}, U+0001 → \u{1}, U+001f → \u{1f}
        assert _kdl_str("\x00") == '"\\u{0}"'
        assert _kdl_str("\x01") == '"\\u{1}"'
        assert _kdl_str("\x1f") == '"\\u{1f}"'

    def test_newline_is_control_char(self) -> None:
        assert _kdl_str("\n") == '"\\u{a}"'

    def test_tab_is_control_char(self) -> None:
        assert _kdl_str("\t") == '"\\u{9}"'

    def test_non_ascii_passthrough(self) -> None:
        # Characters above U+001F and below U+0080 are verbatim;
        # non-ASCII unicode (≥ U+0020) also verbatim
        assert _kdl_str("héllo") == '"héllo"'

    def test_empty_string(self) -> None:
        assert _kdl_str("") == '""'


