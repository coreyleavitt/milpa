class TestFromGraph:
    def _git_prov(
        self,
        url: str = "https://example.com/foo.git",
        ref: str | None = None,
        sha: str | None = None,
    ) -> GitProvenanceRecord:
        return GitProvenanceRecord(url=url, ref=ref, commit_sha=sha)

    def test_empty_graph(self) -> None:
        g = ResolvedGraph(deps=())
        lf = from_graph(g)
        assert lf.deps == ()
        assert lf.strategy == "maxver"

    def test_single_dep(self) -> None:
        prov = self._git_prov(ref="main", sha="dead" * 10)
        d = _make_resolved_dep("foo", version="1.0.0", provenance=prov)
        g = ResolvedGraph(deps=(d,))
        lf = from_graph(g)
        assert len(lf.deps) == 1
        dep = lf.deps[0]
        assert dep.name == "foo"
        assert dep.version == "1.0.0"

    def test_deps_sorted_lexicographically(self) -> None:
        deps = tuple(
            _make_resolved_dep(n, provenance=self._git_prov())
            for n in ["zebra", "apple", "mango"]
        )
        g = ResolvedGraph(deps=deps)
        lf = from_graph(g)
        names = [d.name for d in lf.deps]
        assert names == ["apple", "mango", "zebra"]

    def test_requires_sorted_lexicographically(self) -> None:
        prov = self._git_prov()
        d = _make_resolved_dep("foo", requires=("zoo", "ant", "bee"), provenance=prov)
        g = ResolvedGraph(deps=(d,))
        lf = from_graph(g)
        assert lf.deps[0].requires == ("ant", "bee", "zoo")

    def test_strategy_passed_through(self) -> None:
        g = ResolvedGraph(deps=())
        lf = from_graph(g, strategy="minver")
        assert lf.strategy == "minver"

    def test_no_provenance_dep_gets_empty_provenances(self) -> None:
        d = _make_resolved_dep("foo", provenance=None)
        g = ResolvedGraph(deps=(d,))
        lf = from_graph(g)
        assert lf.deps[0].provenances == ()

    def test_active_flags_and_mirrors_passed_through(self) -> None:
        prov = self._git_prov()
        d = _make_resolved_dep(
            "foo",
            provenance=prov,
            active_flags=("ssl",),
            self_mirrors=("https://mirror.example.com/foo.git",),
        )
        g = ResolvedGraph(deps=(d,))
        lf = from_graph(g)
        dep = lf.deps[0]
        assert dep.active_flags == ("ssl",)
        assert dep.self_mirrors == ("https://mirror.example.com/foo.git",)


