_MINIMAL_LF = Lockfile(version=1, strategy="maxver", deps=())


class TestWriteLockfileAtomic:
    """Phase C / C-atomic: write_lockfile must write atomically via a temp file
    in the same directory as the target, then os.replace — so EXDEV (cross-device
    rename) is structurally impossible.

    Behaviors tested:
      1. Round-trip correctness: parsed-back content equals the original.
      2. No leftover temp files after a successful write (proves rename happened).
      3. Failure cleanup: if the write fails, no temp file is left behind and
         the original target (if it existed) is untouched.
    """

    def test_write_lockfile_round_trips(self, tmp_path: Path) -> None:
        """B1 (tracer): write_lockfile + parse_lockfile is an identity for a
        minimal Lockfile."""
        path = tmp_path / "milpa.lock"
        returned = write_lockfile(_MINIMAL_LF, path)
        assert returned == path
        reparsed = parse_lockfile(path.read_text())
        assert reparsed == _MINIMAL_LF

    def test_write_lockfile_no_leftover_temp(self, tmp_path: Path) -> None:
        """B2 (atomicity): after a successful write no sibling temp files remain.

        The temp file lives in the same directory as the target so that
        os.replace is always same-filesystem (EXDEV structurally impossible).
        Checking for absence of any file matching the temp naming pattern
        (``milpa.lock.tmp*`` or ``*.tmp*``) proves the rename completed.
        """
        path = tmp_path / "milpa.lock"
        write_lockfile(_MINIMAL_LF, path)
        leftovers = [
            f for f in tmp_path.iterdir() if ".tmp" in f.name
        ]
        assert leftovers == [], f"temp files left behind: {leftovers}"

    def test_write_lockfile_no_leftover_temp_with_existing_target(
        self, tmp_path: Path
    ) -> None:
        """B2 variant: no leftover temp even when an existing lockfile is replaced."""
        path = tmp_path / "milpa.lock"
        path.write_text("old content")
        write_lockfile(_MINIMAL_LF, path)
        leftovers = [f for f in tmp_path.iterdir() if ".tmp" in f.name]
        assert leftovers == [], f"temp files left behind: {leftovers}"
        # Confirm the old content was fully replaced
        assert "old content" not in path.read_text()

    def test_write_lockfile_creates_parent_dirs(self, tmp_path: Path) -> None:
        """write_lockfile creates missing parent directories (existing behaviour)."""
        path = tmp_path / "nested" / "deep" / "milpa.lock"
        write_lockfile(_MINIMAL_LF, path)
        assert path.exists()

    def test_write_lockfile_failure_leaves_no_temp(self, tmp_path: Path) -> None:
        """B3 (failure cleanup): if the write fails, no temp file is left.

        We simulate failure by making the target directory read-only so that
        the temp-file creation itself raises PermissionError.  We verify:
          - the exception propagates,
          - no temp file remains in the (inaccessible-for-write) directory.
        """
        target_dir = tmp_path / "ro_dir"
        target_dir.mkdir()
        path = target_dir / "milpa.lock"

        # Make the directory read-only (remove write + execute bits for owner).
        original_mode = target_dir.stat().st_mode
        target_dir.chmod(stat.S_IRUSR | stat.S_IXUSR)
        try:
            with pytest.raises((PermissionError, OSError)):
                write_lockfile(_MINIMAL_LF, path)
            # No temp files should remain (cleanup in except branch).
            leftovers = list(target_dir.iterdir()) if os.access(target_dir, os.R_OK) else []
            assert leftovers == [], f"temp files left after failure: {leftovers}"
        finally:
            target_dir.chmod(original_mode)

    def test_write_lockfile_failure_preserves_existing_target(
        self, tmp_path: Path
    ) -> None:
        """B3 variant: if writing to a temp fails after the original exists, the
        original is untouched.

        We write a valid lockfile, then inject a failure by pointing at a path
        whose *parent* is read-only (so the temp-file creation fails before
        os.replace is ever attempted).
        """
        # Use a writable directory that we later make read-only.
        target_dir = tmp_path / "protected"
        target_dir.mkdir()
        path = target_dir / "milpa.lock"

        # Write a valid lockfile first.
        original_content = format_lockfile(_MINIMAL_LF)
        path.write_text(original_content)

        # Revoke write permission so the temp-file creation fails.
        original_mode = target_dir.stat().st_mode
        target_dir.chmod(stat.S_IRUSR | stat.S_IXUSR)
        try:
            with pytest.raises((PermissionError, OSError)):
                write_lockfile(_MINIMAL_LF, path)
            # The original file should be readable and unchanged.
            if os.access(target_dir, os.R_OK) and os.access(path, os.R_OK):
                assert path.read_text() == original_content
        finally:
            target_dir.chmod(original_mode)

    def test_write_lockfile_failure_cleans_temp_on_rename_error(
        self, tmp_path: Path
    ) -> None:
        """B3 (rename-error path): if the rename step fails, no temp file is
        left behind.

        We simulate a rename failure by making the *target path* an existing
        directory — ``os.replace(file, dir)`` raises ``IsADirectoryError``
        (EISDIR) on POSIX.  This exercises the post-write-pre-rename error
        branch without relying on chmod or root-user behavior.
        """
        path = tmp_path / "milpa.lock"
        # Make the target path an existing directory so rename fails.
        path.mkdir()

        with pytest.raises((IsADirectoryError, OSError)):
            write_lockfile(_MINIMAL_LF, path)

        # No temp files must remain in the parent directory.
        leftovers = [f for f in tmp_path.iterdir() if ".tmp" in f.name]
        assert leftovers == [], f"temp files left after rename failure: {leftovers}"


