class TestVerifyAgainstGraph:
    def _make_lockfile_with(self, name: str, identity: str | None) -> Lockfile:
        prov = GitProvenanceRecord(url="https://example.com/foo.git")
        dep = LockedDep(
            name=name,
            identity=identity,
            version="1.0.0",
            src_dir="",
            requires=(),
            provenances=(prov,),
        )
        return Lockfile(deps=(dep,))

    def _make_graph_with(self, name: str, identity: str | None) -> ResolvedGraph:
        d = ResolvedDep(
            name=name,
            identity=identity,
            version="1.0.0",
            src_dir="",
            requires=(),
        )
        return ResolvedGraph(deps=(d,))

    def test_matching_graph_and_lock_succeeds(self) -> None:
        lf = self._make_lockfile_with("foo", _VALID_IDENTITY)
        g = self._make_graph_with("foo", _VALID_IDENTITY)
        verify_against_graph(lf, g)  # must not raise

    def test_empty_both_succeeds(self) -> None:
        lf = Lockfile(deps=())
        g = ResolvedGraph(deps=())
        verify_against_graph(lf, g)

    def test_dep_in_graph_not_in_lock_raises(self) -> None:
        lf = Lockfile(deps=())
        g = self._make_graph_with("foo", _VALID_IDENTITY)
        with pytest.raises(MilpaError) as exc_info:
            verify_against_graph(lf, g)
        assert exc_info.value.slug == LOCK_GRAPH_MISMATCH
        assert "foo" in exc_info.value.message

    def test_dep_in_lock_not_in_graph_raises(self) -> None:
        lf = self._make_lockfile_with("foo", _VALID_IDENTITY)
        g = ResolvedGraph(deps=())
        with pytest.raises(MilpaError) as exc_info:
            verify_against_graph(lf, g)
        assert exc_info.value.slug == LOCK_GRAPH_MISMATCH
        assert "foo" in exc_info.value.message

    def test_identity_mismatch_raises(self) -> None:
        lf = self._make_lockfile_with("foo", _VALID_IDENTITY)
        other_identity = f"sha256:{'b' * 64}"
        g = self._make_graph_with("foo", other_identity)
        with pytest.raises(MilpaError) as exc_info:
            verify_against_graph(lf, g)
        assert exc_info.value.slug == LOCK_GRAPH_MISMATCH

    def test_none_identity_matches_none(self) -> None:
        lf = self._make_lockfile_with("foo", None)
        g = self._make_graph_with("foo", None)
        verify_against_graph(lf, g)  # must not raise

    def test_multiple_errors_collected(self) -> None:
        """All mismatches are reported, not just the first."""
        prov = GitProvenanceRecord(url="https://example.com/foo.git")
        dep1 = LockedDep(
            name="foo",
            identity=_VALID_IDENTITY,
            version="1.0.0",
            src_dir="",
            requires=(),
            provenances=(prov,),
        )
        dep2 = LockedDep(
            name="bar",
            identity=_VALID_IDENTITY,
            version="1.0.0",
            src_dir="",
            requires=(),
            provenances=(prov,),
        )
        lf = Lockfile(deps=(dep1, dep2))
        # Graph has neither foo nor bar; has baz instead
        g = ResolvedGraph(
            deps=(
                ResolvedDep(
                    name="baz",
                    identity=_VALID_IDENTITY,
                    version="1.0.0",
                    src_dir="",
                    requires=(),
                ),
            )
        )
        with pytest.raises(MilpaError) as exc_info:
            verify_against_graph(lf, g)
        err = exc_info.value
        assert err.slug == LOCK_GRAPH_MISMATCH
        # Multiple dep names should appear in the message
        msg = err.message
        assert "foo" in msg or "bar" in msg or "baz" in msg


