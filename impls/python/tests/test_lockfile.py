# 4c — Fixture-118 byte-exact gate
#
# Spec-canonical test: hand-craft a ResolvedGraph whose dep's ref carries
# both `"` and `\`, call from_graph + format_lockfile, and assert byte-equality
# against conformance/spec-v1/fixture-118-lock-string-escaping/expected/milpa.lock.
# ---------------------------------------------------------------------------


class TestFixture118ByteExact:
    _FIXTURE_PATH = _fixture("fixture-118-lock-string-escaping") / "expected" / "milpa.lock"

    def test_fixture_118_byte_exact(self) -> None:
        """format_lockfile must produce the exact bytes of fixture-118/expected/milpa.lock."""
        # The fixture's manifest declares:
        #   foo git=(url)"https://github.com/example/foo.git" ref="v1\"x\\y"
        # After KDL unescaping: ref = v1"x\y
        # The mocked-fetch entry provides:
        #   sha = abcdef1234567890abcdef1234567890abcdef12
        #   identity = sha256:19f1b5dadf5a74f44e39f7403a519a8a560fbd61b97425d4ade643ee4a52fa59
        #   nimble: version = "1.0.0", srcDir = "src"
        prov = GitProvenanceRecord(
            url="https://github.com/example/foo.git",
            ref='v1"x\\y',                          # literal double-quote + backslash
            commit_sha="abcdef1234567890abcdef1234567890abcdef12",
        )
        dep = ResolvedDep(
            name="foo",
            identity="sha256:19f1b5dadf5a74f44e39f7403a519a8a560fbd61b97425d4ade643ee4a52fa59",
            version="0.0.1",
            src_dir="src",
            requires=(),
            provenance=prov,
        )
        graph = ResolvedGraph(deps=(dep,))
        lf = from_graph(graph, strategy="maxver")
        got = format_lockfile(lf)

        expected = self._FIXTURE_PATH.read_text()
        assert got == expected, (
            f"Byte-exact mismatch with fixture-118.\n"
            f"Expected ({len(expected)} chars):\n{expected!r}\n\n"
            f"Got ({len(got)} chars):\n{got!r}"
        )

    def test_fixture_118_round_trips(self) -> None:
        """Parsing the fixture-118 expected lockfile recovers the ref with escapes intact."""
        expected = self._FIXTURE_PATH.read_text()
        lf = parse_lockfile(expected)
        dep = lf.deps[0]
        prov = dep.provenances[0]
        assert isinstance(prov, GitProvenanceRecord)
        # KDL unescaping: `v1\"x\\y` → v1"x\y
        assert prov.ref == 'v1"x\\y', f"Expected 'v1\"x\\\\y', got {prov.ref!r}"

    def test_format_parse_round_trip(self) -> None:
        """from_graph → format_lockfile → parse_lockfile is identity."""
        prov = GitProvenanceRecord(
            url="https://github.com/example/foo.git",
            ref='v1"x\\y',
            commit_sha="abcdef1234567890abcdef1234567890abcdef12",
        )
        dep = ResolvedDep(
            name="foo",
            identity="sha256:19f1b5dadf5a74f44e39f7403a519a8a560fbd61b97425d4ade643ee4a52fa59",
            version="0.0.1",
            src_dir="src",
            requires=(),
            provenance=prov,
        )
        graph = ResolvedGraph(deps=(dep,))
        lf = from_graph(graph, strategy="maxver")
        text = format_lockfile(lf)
        lf2 = parse_lockfile(text)
        assert len(lf2.deps) == 1
        dep2 = lf2.deps[0]
        prov2 = dep2.provenances[0]
        assert isinstance(prov2, GitProvenanceRecord)
        assert prov2.ref == 'v1"x\\y'


