        nimcfg_b = result["member-b"]
        b_path_lines = [l for l in nimcfg_b.splitlines() if l.startswith("--path:")]
        assert b_path_lines == ['--path:"../member-c"'], (
            f"B has no src_dir; expected only pkg-c dep path, got: {b_path_lines}"
        )

