# §7.6  format_workspace_nimcfgs — per-member relative paths (S9d)
# ---------------------------------------------------------------------------


class TestWorkspaceNimcfgs:
    """format_workspace_nimcfgs emits per-member nim.cfg with relative paths (§7.6)."""

    def _make_workspace(
        self,
        tmp_path: Path,
        members: list[tuple[str, str, str]],  # (name, rel_path, src_dir)
    ) -> object:
        """Build a minimal LoadedWorkspace stub for testing."""
        from milpa.manifest import Manifest, WorkspaceManifest
        from milpa.workspace import LoadedMember, LoadedWorkspace

        loaded_members = []
        for name, rel_path, src_dir in members:
            abs_dir = tmp_path / rel_path
            abs_dir.mkdir(parents=True, exist_ok=True)
            manifest = Manifest(
                name=name,
                kind="library",
                src_dir=src_dir,
                deps=(),
            )
            loaded_members.append(LoadedMember(
                rel_path=rel_path,
                abs_dir=abs_dir,
                manifest=manifest,
            ))

        ws_manifest = WorkspaceManifest(
            members=tuple(m.rel_path for m in loaded_members),
        )
        return LoadedWorkspace(
            root_dir=tmp_path,
            workspace_manifest=ws_manifest,
            members=tuple(loaded_members),
        )

    def test_member_with_no_deps_emits_header_only(self, tmp_path: Path) -> None:
        """A member with no transitive deps gets header-only nim.cfg."""
        from milpa.lockfile import MemberProvenanceRecord
        ws = self._make_workspace(tmp_path, [("liba", "member-a", "src")])
        graph = ResolvedGraph(deps=(
            ResolvedDep(
                name="liba",
                identity="sha256:" + "0" * 64,
                version="0.0.1",
                src_dir="src",
                requires=(),
                provenance=MemberProvenanceRecord(name="liba"),
            ),
        ))
        result = format_workspace_nimcfgs(ws, graph)
        assert "member-a" in result
        nimcfg = result["member-a"]
        assert nimcfg == (
            "# generated by milpa; do not edit\n"
            "# manifest: milpa.kdl\n"
            "# lockfile: milpa.lock\n"
        )

    def test_member_dep_uses_relative_path(self, tmp_path: Path) -> None:
        """A member dep uses a relative path from the member's directory.

        fixture-117: member-b depends on member-a (src_dir="src").
        member-b is at <root>/member-b/; member-a at <root>/member-a/.
        Expected: --path:"../member-a/src"
        """
        from milpa.lockfile import MemberProvenanceRecord
        ws = self._make_workspace(tmp_path, [
            ("liba", "member-a", "src"),
            ("libb", "member-b", "src"),
        ])
        graph = ResolvedGraph(deps=(
            ResolvedDep(
                name="liba",
                identity="sha256:" + "a" * 64,
                version="0.0.1",
                src_dir="src",
                requires=(),
                provenance=MemberProvenanceRecord(name="liba"),
            ),
            ResolvedDep(
                name="libb",
                identity="sha256:" + "b" * 64,
                version="0.0.1",
                src_dir="src",
                requires=("liba",),
                provenance=MemberProvenanceRecord(name="libb"),
            ),
        ))
        result = format_workspace_nimcfgs(ws, graph)
        assert "member-b" in result
        nimcfg_b = result["member-b"]
        # member-b depends on liba (src_dir="src") → ../member-a/src
        assert '--path:"../member-a/src"' in nimcfg_b

    def test_all_members_returned(self, tmp_path: Path) -> None:
        """All declared members appear in the returned dict."""
        from milpa.lockfile import MemberProvenanceRecord
        ws = self._make_workspace(tmp_path, [
            ("liba", "member-a", ""),
            ("libb", "member-b", ""),
        ])
        graph = ResolvedGraph(deps=(
            ResolvedDep(
                name="liba",
                identity="sha256:" + "0" * 64,
                version="0.0.1",
                src_dir="",
                requires=(),
                provenance=MemberProvenanceRecord(name="liba"),
            ),
            ResolvedDep(
                name="libb",
                identity="sha256:" + "1" * 64,
                version="0.0.1",
                src_dir="",
                requires=(),
                provenance=MemberProvenanceRecord(name="libb"),
            ),
        ))
        result = format_workspace_nimcfgs(ws, graph)
        assert set(result.keys()) == {"member-a", "member-b"}


