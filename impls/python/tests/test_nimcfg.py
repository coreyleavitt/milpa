class TestPathLineForm:
    """--path:"<deps_dir>/<name>[/<src_dir>]" form (§7.3)."""

    def test_empty_src_dir_omits_trailing_slash(self) -> None:
        graph = ResolvedGraph(deps=(_dep("zlib", ""),))
        out = format_nimcfg(graph)
        assert '--path:"_deps/zlib"' in out
        assert '--path:"_deps/zlib/"' not in out

    def test_src_dir_appended_with_slash(self) -> None:
        graph = ResolvedGraph(deps=(_dep("chronos", "chronos"),))
        out = format_nimcfg(graph)
        assert '--path:"_deps/chronos/chronos"' in out

    def test_custom_deps_dir(self) -> None:
        graph = ResolvedGraph(deps=(_dep("foo", "src"),))
        out = format_nimcfg(graph, deps_dir=Path("third_party"))
        assert '--path:"third_party/foo/src"' in out

    def test_nested_src_dir(self) -> None:
        graph = ResolvedGraph(deps=(_dep("pkg", "lib/nim"),))
        out = format_nimcfg(graph)
        assert '--path:"_deps/pkg/lib/nim"' in out


# ---------------------------------------------------------------------------
# §7.4  Emission order
# ---------------------------------------------------------------------------


class TestEmissionOrder:
    """Emission order: self src-dir first, then deps sorted lexicographically (§7.4)."""

    def test_no_deps_header_only(self) -> None:
        """No-deps: header only, trailing \\n (no blank line after header)."""
        graph = ResolvedGraph(deps=())
        out = format_nimcfg(graph)
        # Must not contain --path:
        assert "--path:" not in out
        # Must end with a single \n (not \n\n)
        assert out.endswith("milpa.lock\n")
        assert not out.endswith("milpa.lock\n\n")

    def test_no_deps_no_blank_line_after_header(self) -> None:
        graph = ResolvedGraph(deps=())
        out = format_nimcfg(graph)
        # No double-newline
        assert "\n\n" not in out

    def test_self_src_dir_before_deps(self) -> None:
        graph = ResolvedGraph(deps=(_dep("foo", "src"),))
        out = format_nimcfg(graph, self_src_dir="src")
        self_idx = out.index('--path:"src"')
        dep_idx = out.index('--path:"_deps/foo/src"')
        assert self_idx < dep_idx

    def test_self_src_dir_only_no_deps(self) -> None:
        """Self src-dir with no deps: header + blank line + self path line."""
        graph = ResolvedGraph(deps=())
        out = format_nimcfg(graph, self_src_dir="src")
        assert "--path:" in out
        lines = out.splitlines()
        # 0: # generated…, 1: # manifest…, 2: # lockfile…, 3: (blank), 4: --path:"src"
        assert lines[3] == ""
        assert lines[4] == '--path:"src"'

    def test_deps_lexicographic_order(self) -> None:
        """Deps sorted lexicographically regardless of graph construction order."""
        # Graph has deps in reverse-alpha order
        graph = ResolvedGraph(deps=(_dep("zlib"), _dep("alpha"), _dep("mod")))
        out = format_nimcfg(graph)
        path_lines = [ln for ln in out.splitlines() if ln.startswith("--path:")]
        names_in_output = [ln.split("/")[1].rstrip('"') for ln in path_lines]
        assert names_in_output == sorted(names_in_output)

    def test_trailing_newline_single_dep(self) -> None:
        """File ends with exactly one trailing \\n (§7.4 NOTE)."""
        graph = ResolvedGraph(deps=(_dep("foo", "src"),))
        out = format_nimcfg(graph)
        assert out.endswith("\n")
        assert not out.endswith("\n\n")

    def test_blank_line_separates_header_from_paths(self) -> None:
        graph = ResolvedGraph(deps=(_dep("foo", "src"),))
        out = format_nimcfg(graph)
        lines = out.splitlines()
        # line 3 (index 3) must be blank
        assert lines[3] == ""
        # line 4 is the first --path:
        assert lines[4].startswith("--path:")

    def test_multiple_deps_sorted(self) -> None:
        graph = ResolvedGraph(
            deps=(_dep("zz", ""), _dep("aa", "src"), _dep("mm", "lib"))
        )
        out = format_nimcfg(graph)
        path_lines = [ln for ln in out.splitlines() if ln.startswith("--path:")]
        assert path_lines[0] == '--path:"_deps/aa/src"'
        assert path_lines[1] == '--path:"_deps/mm/lib"'
        assert path_lines[2] == '--path:"_deps/zz"'


