class TestDeterminism:
    """Same graph always produces byte-identical output (§2.4 / §7.2)."""

    def test_same_graph_same_output(self) -> None:
        deps = (_dep("b", "src"), _dep("a", "lib"), _dep("c", ""))
        graph = ResolvedGraph(deps=deps)
        assert format_nimcfg(graph) == format_nimcfg(graph)

    def test_graph_order_independent(self) -> None:
        """Permuting the deps tuple must not change the output."""
        g1 = ResolvedGraph(deps=(_dep("aa"), _dep("bb"), _dep("cc")))
        g2 = ResolvedGraph(deps=(_dep("cc"), _dep("aa"), _dep("bb")))
        g3 = ResolvedGraph(deps=(_dep("bb"), _dep("cc"), _dep("aa")))
        result = format_nimcfg(g1)
        assert format_nimcfg(g2) == result
        assert format_nimcfg(g3) == result
