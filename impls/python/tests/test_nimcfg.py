from pathlib import Path

from milpa.lockfile import ResolvedDep, ResolvedGraph
from milpa.nimcfg import format_nimcfg, format_workspace_nimcfgs

# ---------------------------------------------------------------------------
# Fixtures helpers
# ---------------------------------------------------------------------------

_CONFORMANCE = Path(__file__).parent.parent.parent.parent / "conformance" / "spec-v1"


def _expected_nimcfg(fixture_name: str, subpath: str = "nim.cfg") -> str:
    """Load an expected nim.cfg from the conformance corpus."""
    path = _CONFORMANCE / fixture_name / "expected" / subpath
    return path.read_text()


def _dep(
    name: str,
    src_dir: str = "",
    requires: tuple[str, ...] = (),
    active_flags: tuple[str, ...] = (),
) -> ResolvedDep:
    """Build a minimal ResolvedDep suitable for nimcfg tests."""
    return ResolvedDep(
        name=name,
        identity=None,
        version="0.0.1",
        src_dir=src_dir,
        requires=requires,
        active_flags=active_flags,
    )


# ---------------------------------------------------------------------------
# §7.1  Header
# ---------------------------------------------------------------------------


class TestHeader:
    """The normative three-line header MUST be emitted unconditionally (§7.1)."""

    _HEADER = (
        "# generated by milpa; do not edit\n"
        "# manifest: milpa.kdl\n"
        "# lockfile: milpa.lock\n"
    )

    def test_header_present_with_no_deps(self) -> None:
        graph = ResolvedGraph(deps=())
        out = format_nimcfg(graph)
        assert out.startswith(self._HEADER.rstrip("\n"))

    def test_header_present_with_deps(self) -> None:
        graph = ResolvedGraph(deps=(_dep("foo", "src"),))
        out = format_nimcfg(graph)
        assert out.startswith("# generated by milpa; do not edit\n")
        assert "# manifest: milpa.kdl\n" in out
        assert "# lockfile: milpa.lock\n" in out

    def test_header_is_exactly_three_lines(self) -> None:
        graph = ResolvedGraph(deps=())
        out = format_nimcfg(graph)
        header_block = out.split("\n\n")[0]  # up to first blank line (or all)
        lines = header_block.splitlines()
        assert lines[0] == "# generated by milpa; do not edit"
        assert lines[1] == "# manifest: milpa.kdl"
        assert lines[2] == "# lockfile: milpa.lock"


# ---------------------------------------------------------------------------
# §7.2  POSIX path separators
# ---------------------------------------------------------------------------


class TestPosixPaths:
    """All --path: lines MUST use / regardless of host OS (§7.2)."""

    def test_no_backslashes_in_dep_path(self) -> None:
        graph = ResolvedGraph(deps=(_dep("mydep", "some/sub"),))
        out = format_nimcfg(graph, deps_dir=Path("_deps"))
        # Every --path: line must not contain backslash
        path_lines = [ln for ln in out.splitlines() if ln.startswith("--path:")]
        assert all("\\" not in ln for ln in path_lines)

    def test_forward_slash_separator(self) -> None:
        graph = ResolvedGraph(deps=(_dep("lib", "sources"),))
        out = format_nimcfg(graph, deps_dir=Path("_deps"))
        assert '--path:"_deps/lib/sources"' in out

    def test_deps_dir_uses_posix(self) -> None:
        # Even if Path() uses native sep on Windows, as_posix() must be used.
        graph = ResolvedGraph(deps=(_dep("x", ""),))
        out = format_nimcfg(graph, deps_dir=Path("vendor") / "deps")
        assert '--path:"vendor/deps/x"' in out


