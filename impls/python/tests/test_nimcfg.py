class TestWorkspaceSelfSrcDir:
    """S7: format_workspace_nimcfgs emits self-src-dir first for each member (§3.D).

    Ordering is normative (Breadth-P3d): self-src_dir FIRST, then all deps
    lex-sorted by name — exactly the single-package format_nimcfg rule.
    """

    def _make_workspace(
        self,
        tmp_path: Path,
        members: list[tuple[str, str, str]],  # (name, rel_path, src_dir)
    ) -> object:
        from milpa.manifest import Manifest, WorkspaceManifest
        from milpa.workspace import LoadedMember, LoadedWorkspace

        loaded_members = []
        for name, rel_path, src_dir in members:
            abs_dir = tmp_path / rel_path
            abs_dir.mkdir(parents=True, exist_ok=True)
            manifest = Manifest(
                name=name,
                kind="library",
                src_dir=src_dir,
                deps=(),
            )
            loaded_members.append(LoadedMember(
                rel_path=rel_path,
                abs_dir=abs_dir,
                manifest=manifest,
            ))

        ws_manifest = WorkspaceManifest(
            members=tuple(m.rel_path for m in loaded_members),
        )
        return LoadedWorkspace(
            root_dir=tmp_path,
            workspace_manifest=ws_manifest,
            members=tuple(loaded_members),
        )

    def test_s7_member_self_src_dir_emitted_before_deps(self, tmp_path: Path) -> None:
        """S7: member A has src_dir='src'; its nim.cfg emits --path:'src' FIRST.

        Scenario (3-member chain: A→B, B→C):
          - A has src_dir='src'; B and C have no src_dir.
          - A's nim.cfg must emit --path:'src' before any dep paths.
          - B's nim.cfg has no self src-dir to emit (B has no src_dir).
          - C's nim.cfg is header-only (no deps).
        """
        from milpa.lockfile import MemberProvenanceRecord

        ws = self._make_workspace(tmp_path, [
            ("pkg-a", "member-a", "src"),   # A has src_dir
            ("pkg-b", "member-b", ""),       # B has no src_dir
            ("pkg-c", "member-c", ""),       # C has no src_dir
        ])
        dep_c = ResolvedDep(
            name="pkg-c",
            identity="sha256:" + "c" * 64,
            version="0.0.1",
            src_dir="",
            requires=(),
            provenances=(MemberProvenanceRecord(name="pkg-c"),),
        )
        dep_b = ResolvedDep(
            name="pkg-b",
            identity="sha256:" + "b" * 64,
            version="0.0.1",
            src_dir="",
            requires=("pkg-c",),
            provenances=(MemberProvenanceRecord(name="pkg-b"),),
        )
        dep_a = ResolvedDep(
            name="pkg-a",
            identity="sha256:" + "a" * 64,
            version="0.0.1",
            src_dir="src",
            requires=("pkg-b",),
            provenances=(MemberProvenanceRecord(name="pkg-a"),),
        )
        graph = ResolvedGraph(deps=(dep_a, dep_b, dep_c))
        result = format_workspace_nimcfgs(ws, graph)

        nimcfg_a = result["member-a"]
        lines = [l for l in nimcfg_a.splitlines() if l.startswith("--path:")]

        # self src-dir must be FIRST
        assert lines[0] == '--path:"src"', (
            f"Expected self src-dir first in A's nim.cfg, got: {lines}"
        )
        # then dep paths lex-sorted by name: pkg-b before pkg-c
        assert '--path:"../member-b"' in nimcfg_a
        assert '--path:"../member-c"' in nimcfg_a
        pkg_b_pos = nimcfg_a.index('../member-b')
        pkg_c_pos = nimcfg_a.index('../member-c')
        assert pkg_b_pos < pkg_c_pos, "deps must be lex-sorted: pkg-b before pkg-c"

