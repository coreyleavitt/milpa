//! `milpa.kdl` serialization (RFC §6 S13; manifest-grammar §8; mirrors
//! `manifest.py:format_manifest`).
//!
//! The inverse of the package parser: render a [`Manifest`] back to canonical
//! `milpa.kdl` text. Deterministic, **insertion-stable** dep order, URL/tarball
//! values carry the recommended `(url)` annotation. Comment-preserving
//! serialization is out of scope (the mutating verbs warn that hand-written
//! comments are dropped on rewrite).

use crate::{Dep, Manifest, OverrideTarget, Predicate, Workspace};

const HEADER: &str = "// generated by milpa; edit by hand or via `milpa add` / `milpa remove`";

/// Escape a string for KDL 2.0 double-quoted form.
///
/// Matches Python's `_kdl_str` byte-for-byte (manifest.py:~2408):
/// backslash → `\\`, double-quote → `\"`, newline → `\n`,
/// carriage-return → `\r`, tab → `\t`.  Backslash is replaced first so
/// that the subsequent replacements do not double-escape the newly inserted
/// backslashes.
fn kdl_str(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}

/// Render a [`crate::TrustPolicy`] to its manifest wire string.
fn trust_policy_str(p: &crate::TrustPolicy) -> &'static str {
    match p {
        crate::TrustPolicy::Strict => "strict",
        crate::TrustPolicy::Warn => "warn",
        crate::TrustPolicy::Off => "off",
    }
}

/// Render one `overrides {}` `pkg` rule (S8/S8b, rfc-origin-as-identity.md
/// §7 B5) — single source of truth shared by `format_manifest` and
/// `format_workspace_manifest` (both packages and a workspace root use the
/// IDENTICAL override grammar; mirrors Python's `_format_override_line`,
/// which unifies the same previously-duplicated logic). Returns the line(s)
/// to push (more than one only for the `Member` block form).
fn format_override_lines(ov: &crate::Override) -> Vec<String> {
    let version_suffix = ov
        .version
        .as_ref()
        .map(|v| format!(" version=\"{}\"", milpa_solver::format_version_str(v)))
        .unwrap_or_default();
    match &ov.target {
        OverrideTarget::Git { url, git_ref, subpath } => {
            let subpath_suffix = subpath
                .as_ref()
                .map(|s| format!(" subpath=\"{}\"", kdl_str(s)))
                .unwrap_or_default();
            vec![format!(
                "    pkg \"{}\" git=(url)\"{}\" ref=\"{}\"{}{}",
                kdl_str(&ov.name), kdl_str(url), kdl_str(git_ref), subpath_suffix, version_suffix
            )]
        }
        OverrideTarget::Local { path } => {
            vec![format!(
                "    pkg \"{}\" local=\"{}\"{}",
                kdl_str(&ov.name), kdl_str(path), version_suffix
            )]
        }
        OverrideTarget::Oci { registry, repository, digest, subpath } => {
            let subpath_suffix = subpath
                .as_ref()
                .map(|s| format!(" subpath=\"{}\"", kdl_str(s)))
                .unwrap_or_default();
            vec![format!(
                "    pkg \"{}\" oci=\"{}/{}\" digest=\"{}\"{}{}",
                kdl_str(&ov.name), kdl_str(registry), kdl_str(repository), kdl_str(digest),
                subpath_suffix, version_suffix
            )]
        }
        OverrideTarget::Tarball { url, sha256, strip_components, subpath } => {
            let mut parts = vec![
                format!("    pkg \"{}\"", kdl_str(&ov.name)),
                format!("tarball=(url)\"{}\"", kdl_str(url)),
            ];
            if let Some(s) = sha256 {
                parts.push(format!("sha256=\"{}\"", kdl_str(s)));
            }
            if *strip_components != 0 {
                parts.push(format!("strip_components={strip_components}"));
            }
            if let Some(s) = subpath {
                parts.push(format!("subpath=\"{}\"", kdl_str(s)));
            }
            if let Some(v) = &ov.version {
                parts.push(format!("version=\"{}\"", milpa_solver::format_version_str(v)));
            }
            vec![parts.join(" ")]
        }
        OverrideTarget::Registry { name, namespace } => {
            let ns_suffix = namespace
                .as_ref()
                .map(|ns| format!(" namespace=\"{}\"", kdl_str(ns)))
                .unwrap_or_default();
            vec![format!(
                "    pkg \"{}\" named=\"{}\"{}{}",
                kdl_str(&ov.name), kdl_str(name), ns_suffix, version_suffix
            )]
        }
        OverrideTarget::Member { member_name } => {
            vec![
                format!("    pkg \"{}\"{} {{", kdl_str(&ov.name), version_suffix),
                format!("        member \"{}\"", kdl_str(member_name)),
                "    }".to_string(),
            ]
        }
    }
}

/// Render a [`Manifest`] to `milpa.kdl` text (trailing newline included).
pub fn format_manifest(m: &Manifest) -> String {
    let mut lines: Vec<String> = vec![HEADER.to_string(), String::new()];

    if m.spec_version_explicit {
        lines.push(format!("spec-version {}", m.spec_version));
        lines.push(String::new());
    }
    if let Some(name) = &m.name {
        lines.push(format!("name \"{}\"", kdl_str(name)));
        lines.push(String::new());
    }
    // version — A1 (§3 Axis A (b) step 1): the package's own declared release
    // version, present iff `m.version` is set (absent-stays-absent, mirroring
    // spec-version above — no default value to fall back to).
    if let Some(version) = &m.version {
        lines.push(format!("version \"{}\"", milpa_solver::format_version_str(version)));
        lines.push(String::new());
    }
    // resolution { strategy "..."; exclude-newer "..." } — C3 (§3 Axis C /
    // §5) + D1 (§3 Axis D). Emitted only when there is actual content
    // (either child set); an empty/absent block is behaviorally identical
    // at the effective-strategy/exclude-newer precedence point, so there is
    // nothing to preserve on round-trip for the empty case.
    if let Some(resolution) = m.resolution {
        if resolution.strategy.is_some() || resolution.exclude_newer.is_some() {
            lines.push("resolution {".to_string());
            if let Some(strategy) = resolution.strategy {
                lines.push(format!("    strategy \"{}\"", strategy.as_str()));
            }
            if let Some(ts) = resolution.exclude_newer {
                lines.push(format!(
                    "    exclude-newer \"{}\"",
                    milpa_types::format_iso8601_timestamp(&ts)
                ));
            }
            lines.push("}".to_string());
            lines.push(String::new());
        }
    }
    if !m.src_dir.is_empty() {
        lines.push(format!("src_dir \"{}\"", kdl_str(&m.src_dir)));
        lines.push(String::new());
    }
    if !m.cas_dir.is_empty() {
        lines.push("cas {".to_string());
        lines.push(format!("    dir \"{}\"", kdl_str(&m.cas_dir)));
        lines.push("}".to_string());
        lines.push(String::new());
    }
    if !m.deps.is_empty() {
        lines.push("deps {".to_string());
        for dep in &m.deps {
            lines.push(format_dep_line(dep));
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }
    if !m.dev_deps.is_empty() {
        lines.push("dev-deps {".to_string());
        for dep in &m.dev_deps {
            lines.push(format_dep_line(dep));
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }
    if !m.overrides.is_empty() {
        lines.push("overrides {".to_string());
        for ov in &m.overrides {
            lines.extend(format_override_lines(ov));
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }
    if !m.self_mirrors.is_empty() {
        lines.push("mirrors {".to_string());
        for url in &m.self_mirrors {
            lines.push(format!("    mirror (url)\"{}\"", kdl_str(url)));
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }
    // provides { module "..." ... } — S7 (rfc-origin-as-identity.md §4.6).
    if !m.provides.is_empty() {
        lines.push("provides {".to_string());
        for module in &m.provides {
            lines.push(format!("    module \"{}\"", kdl_str(module)));
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }
    // S7: skip auto-injected flags (implied by `optional=#true` on the dep).
    let explicit_flags: Vec<_> = m
        .flags
        .iter()
        .filter(|fd| !m.optional_auto_flags.contains(&fd.name))
        .collect();
    if !explicit_flags.is_empty() {
        lines.push("flags {".to_string());
        for fd in explicit_flags {
            let mut head = format!(
                "    \"{}\" default={}",
                kdl_str(&fd.name),
                if fd.default { "#true" } else { "#false" }
            );
            if !fd.description.is_empty() {
                head.push_str(&format!(" description=\"{}\"", kdl_str(&fd.description)));
            }
            let has_block = !fd.defines.is_empty()
                || !fd.enables_same_pkg.is_empty()
                || !fd.enables_cross_pkg.is_empty()
                || !fd.conflicts.is_empty();
            if !has_block {
                lines.push(head);
            } else {
                lines.push(format!("{head} {{"));
                if !fd.defines.is_empty() {
                    let args: Vec<String> =
                        fd.defines.iter().map(|d| format!("\"{}\"", kdl_str(d))).collect();
                    lines.push(format!("        defines {}", args.join(" ")));
                }
                // enables — canonical single-node form (RFC §3.1.1).
                if !fd.enables_same_pkg.is_empty() || !fd.enables_cross_pkg.is_empty() {
                    let same_pkg_args: Vec<String> = fd
                        .enables_same_pkg
                        .iter()
                        .map(|n| format!("\"{}\"", kdl_str(n)))
                        .collect();
                    if fd.enables_cross_pkg.is_empty() {
                        // No cross-pkg: single-line form.
                        lines.push(format!("        enables {}", same_pkg_args.join(" ")));
                    } else {
                        // Cross-pkg present: block form.
                        let enables_head = if same_pkg_args.is_empty() {
                            "        enables".to_string()
                        } else {
                            format!("        enables {}", same_pkg_args.join(" "))
                        };
                        lines.push(format!("{enables_head} {{"));
                        for cpe in &fd.enables_cross_pkg {
                            // cpe.dep is charset-validated [A-Za-z0-9_-]+ — emitted bare.
                            if cpe.flag_requests.is_empty() {
                                lines.push(format!("            {}", cpe.dep));
                            } else {
                                lines.push(format!("            {} {{", cpe.dep));
                                for fr in &cpe.flag_requests {
                                    if fr.enabled {
                                        lines.push(format!("                flag \"{}\"", kdl_str(&fr.name)));
                                    } else {
                                        lines.push(format!(
                                            "                flag \"{}\" #false",
                                            kdl_str(&fr.name)
                                        ));
                                    }
                                }
                                lines.push("            }".to_string());
                            }
                        }
                        lines.push("        }".to_string());
                    }
                }
                if !fd.conflicts.is_empty() {
                    let conflict_args: Vec<String> =
                        fd.conflicts.iter().map(|n| format!("\"{}\"", kdl_str(n))).collect();
                    lines.push(format!("        conflicts {}", conflict_args.join(" ")));
                }
                lines.push("    }".to_string());
            }
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }

    // index-trust / index-trust-signer / index-trust-bundle / entry-trust /
    // index-history — emitted AFTER deps/dev-deps/overrides/mirrors/provides/flags
    // and immediately before `kind` (the canonical order, byte-identical to
    // manifest.py's serializer). present-stays-present / absent-stays-absent:
    // *_explicit (not a non-default-value check) triggers emission, matching the
    // WS-INDEX-TRUST-ON-MEMBER "WHERE it's declared, not what value" semantics.
    // Without this, add / remove / add-member / remove-member round-trips
    // silently reverted a declared policy back to warn — a fail-open.
    if m.index_trust_policy_explicit {
        lines.push(format!("index-trust \"{}\"", trust_policy_str(&m.index_trust_policy)));
        lines.push(String::new());
    }
    if let Some(signer) = &m.index_trust_signer {
        lines.push(format!("index-trust-signer \"{}\"", kdl_str(signer)));
        lines.push(String::new());
    }
    if let Some(bundle) = &m.index_trust_bundle {
        lines.push(format!("index-trust-bundle \"{}\"", kdl_str(bundle)));
        lines.push(String::new());
    }
    if m.entry_trust_policy_explicit {
        lines.push(format!("entry-trust \"{}\"", trust_policy_str(&m.entry_trust_policy)));
        lines.push(String::new());
    }
    if m.index_history_policy_explicit {
        lines.push(format!("index-history \"{}\"", trust_policy_str(&m.index_history_policy)));
        lines.push(String::new());
    }

    lines.push(format!("kind \"{}\"", kdl_str(&m.kind)));
    let mut out = lines.join("\n");
    out.push('\n');
    out
}

const WORKSPACE_HEADER: &str =
    "// generated by milpa; edit by hand or via `milpa workspace add-member` / `milpa workspace remove-member`";

/// Render a [`Workspace`] to `milpa.kdl` text (trailing newline included).
///
/// Byte-identical to the Python `manifest.py:format_workspace_manifest`.
/// Comments are dropped (canonical re-serialization — manifest-grammar §8 + §3.F).
pub fn format_workspace_manifest(ws: &Workspace) -> String {
    let mut lines: Vec<String> = vec![WORKSPACE_HEADER.to_string(), String::new()];

    // name (optional on workspace root)
    if let Some(name) = &ws.name {
        lines.push(format!("name \"{}\"", kdl_str(name)));
        lines.push(String::new());
    }

    // resolution { strategy "..."; exclude-newer "..." } — C3 (§3 Axis C /
    // §5) + D1 (§3 Axis D), root-only. Emitted right after `name`.
    // (index-trust/entry-trust/index-history are now emitted after the
    // workspace/overrides/flags blocks, matching manifest.py — see below.)
    if let Some(resolution) = ws.resolution {
        if resolution.strategy.is_some() || resolution.exclude_newer.is_some() {
            lines.push("resolution {".to_string());
            if let Some(strategy) = resolution.strategy {
                lines.push(format!("    strategy \"{}\"", strategy.as_str()));
            }
            if let Some(ts) = resolution.exclude_newer {
                lines.push(format!(
                    "    exclude-newer \"{}\"",
                    milpa_types::format_iso8601_timestamp(&ts)
                ));
            }
            lines.push("}".to_string());
            lines.push(String::new());
        }
    }

    // workspace { member "..." }
    lines.push("workspace {".to_string());
    for member_path in &ws.members {
        lines.push(format!("    member \"{}\"", kdl_str(member_path)));
    }
    lines.push("}".to_string());
    lines.push(String::new());

    // overrides { pkg "name" ... }
    if !ws.overrides.is_empty() {
        lines.push("overrides {".to_string());
        for ov in &ws.overrides {
            lines.extend(format_override_lines(ov));
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }

    // flags { "<name>" default=#true/#false ... }
    // Workspace flags: no optional-auto-flags to skip (workspace has no deps).
    if !ws.flags.is_empty() {
        lines.push("flags {".to_string());
        for fd in &ws.flags {
            let mut head = format!(
                "    \"{}\" default={}",
                kdl_str(&fd.name),
                if fd.default { "#true" } else { "#false" }
            );
            if !fd.description.is_empty() {
                head.push_str(&format!(" description=\"{}\"", kdl_str(&fd.description)));
            }
            let has_block = !fd.defines.is_empty()
                || !fd.enables_same_pkg.is_empty()
                || !fd.enables_cross_pkg.is_empty()
                || !fd.conflicts.is_empty();
            if !has_block {
                lines.push(head);
            } else {
                lines.push(format!("{head} {{"));
                if !fd.defines.is_empty() {
                    let args: Vec<String> =
                        fd.defines.iter().map(|d| format!("\"{}\"", kdl_str(d))).collect();
                    lines.push(format!("        defines {}", args.join(" ")));
                }
                if !fd.enables_same_pkg.is_empty() || !fd.enables_cross_pkg.is_empty() {
                    let same_pkg_args: Vec<String> = fd
                        .enables_same_pkg
                        .iter()
                        .map(|n| format!("\"{}\"", kdl_str(n)))
                        .collect();
                    if fd.enables_cross_pkg.is_empty() {
                        lines.push(format!("        enables {}", same_pkg_args.join(" ")));
                    } else {
                        let enables_head = if same_pkg_args.is_empty() {
                            "        enables".to_string()
                        } else {
                            format!("        enables {}", same_pkg_args.join(" "))
                        };
                        lines.push(format!("{enables_head} {{"));
                        for cpe in &fd.enables_cross_pkg {
                            // cpe.dep is charset-validated [A-Za-z0-9_-]+ — emitted bare.
                            if cpe.flag_requests.is_empty() {
                                lines.push(format!("            {}", cpe.dep));
                            } else {
                                lines.push(format!("            {} {{", cpe.dep));
                                for fr in &cpe.flag_requests {
                                    if fr.enabled {
                                        lines.push(format!("                flag \"{}\"", kdl_str(&fr.name)));
                                    } else {
                                        lines.push(format!(
                                            "                flag \"{}\" #false",
                                            kdl_str(&fr.name)
                                        ));
                                    }
                                }
                                lines.push("            }".to_string());
                            }
                        }
                        lines.push("        }".to_string());
                    }
                }
                if !fd.conflicts.is_empty() {
                    let conflict_args: Vec<String> =
                        fd.conflicts.iter().map(|n| format!("\"{}\"", kdl_str(n))).collect();
                    lines.push(format!("        conflicts {}", conflict_args.join(" ")));
                }
                lines.push("    }".to_string());
            }
        }
        lines.push("}".to_string());
        lines.push(String::new());
    }

    // index-trust / index-trust-signer / index-trust-bundle / entry-trust /
    // index-history — root-authority policy fields (spec §3.4.7: the workspace
    // root is the resolution root for these). Emitted AFTER the workspace block,
    // overrides, and flags — byte-identical to manifest.py's workspace
    // serializer (resolving the previously out-of-scope Python/Rust ordering
    // divergence). Emission is keyed on *_explicit (present-stays-present /
    // absent-stays-absent), NOT on the value, so a redundant `index-trust
    // "warn"` survives a format→parse round trip instead of silently reverting.
    if ws.index_trust_policy_explicit {
        lines.push(format!("index-trust \"{}\"", trust_policy_str(&ws.index_trust_policy)));
        lines.push(String::new());
    }
    if let Some(signer) = &ws.index_trust_signer {
        lines.push(format!("index-trust-signer \"{}\"", kdl_str(signer)));
        lines.push(String::new());
    }
    if let Some(bundle) = &ws.index_trust_bundle {
        lines.push(format!("index-trust-bundle \"{}\"", kdl_str(bundle)));
        lines.push(String::new());
    }
    if ws.entry_trust_policy_explicit {
        lines.push(format!("entry-trust \"{}\"", trust_policy_str(&ws.entry_trust_policy)));
        lines.push(String::new());
    }
    if ws.index_history_policy_explicit {
        lines.push(format!("index-history \"{}\"", trust_policy_str(&ws.index_history_policy)));
        lines.push(String::new());
    }

    // Strip trailing blank lines so the file ends cleanly after the last block.
    while lines.last().map(|l| l.is_empty()).unwrap_or(false) {
        lines.pop();
    }

    let mut out = lines.join("\n");
    out.push('\n');
    out
}

/// Render a sequence of single-value predicates as inline KDL properties.
///
/// Used to build the property string for a `when` node header.
/// All predicates MUST have exactly one value (multi-value predicates can only
/// appear on UrlDep child nodes, never on `when` node headers).
///
/// Returns a space-prefixed string like ` platform="linux" flag="extras"`
/// or an empty string when `preds` is empty.
fn format_predicate_props(preds: &[&Predicate]) -> String {
    let mut parts: Vec<String> = Vec::new();
    for pred in preds {
        debug_assert_eq!(
            pred.values.len(),
            1,
            "format_predicate_props: predicate {:?} has {} values — only single-value predicates \
             are valid on `when` node headers",
            pred.name,
            pred.values.len()
        );
        let v = &pred.values[0];
        if pred.negated {
            parts.push(format!("{}=(not)\"{}\"", pred.name, kdl_str(v)));
        } else {
            parts.push(format!("{}=\"{}\"", pred.name, kdl_str(v)));
        }
    }
    if parts.is_empty() {
        String::new()
    } else {
        format!(" {}", parts.join(" "))
    }
}

/// One deps-block child as a KDL line (or multi-line block for a URL dep with
/// mirrors / multi-value predicates / flag requests).
///
/// §8 round-trip: deps with explicit when-predicates are wrapped in a
/// `when <preds> { <dep-node> }` grouping block so their predicates survive
/// a format → parse cycle.  UrlDep predicates are emitted inline/as child-nodes
/// on the dep node itself (existing behaviour preserved).  For NamedDep,
/// LocalDep, TarballDep, and MemberDep the wrapping form is the only valid
/// form because those node types do not accept predicate properties directly.
fn format_dep_line(dep: &Dep) -> String {
    match dep {
        Dep::Url(u) => {
            let mut head = format!(
                "    \"{}\" git=(url)\"{}\" ref=\"{}\"",
                kdl_str(&u.name), kdl_str(&u.git), kdl_str(&u.git_ref)
            );
            // version= annotation — A3b (§3 Axis A (b) step 4), Cargo's
            // {git, ref, version} pattern. Present iff u.version is set.
            if let Some(version) = &u.version {
                head.push_str(&format!(" version=\"{}\"", milpa_solver::format_version_str(version)));
            }
            // subpath= — rfc-origin-as-identity.md §4.1/S8. Present iff u.subpath is set.
            if let Some(subpath) = &u.subpath {
                head.push_str(&format!(" subpath=\"{}\"", kdl_str(subpath)));
            }
            // S7: emit `optional=#true` and strip the auto-injected gate predicate.
            if u.optional {
                head.push_str(" optional=#true");
            }
            let serializable_preds: Vec<&_> = if u.optional {
                let auto_gate_name = "flag";
                let auto_gate_val = u.name.as_str();
                u.predicates
                    .iter()
                    .filter(|p| {
                        !(p.name == auto_gate_name
                            && p.values.len() == 1
                            && p.values[0] == auto_gate_val
                            && !p.negated)
                    })
                    .collect()
            } else {
                u.predicates.iter().collect()
            };
            let inline: Vec<&_> = serializable_preds
                .iter()
                .copied()
                .filter(|p| p.values.len() == 1)
                .collect();
            let child: Vec<&_> = serializable_preds
                .iter()
                .copied()
                .filter(|p| p.values.len() > 1)
                .collect();
            for p in &inline {
                let v = &p.values[0];
                if p.negated {
                    head.push_str(&format!(" {}=(not)\"{}\"", p.name, kdl_str(v)));
                } else {
                    head.push_str(&format!(" {}=\"{}\"", p.name, kdl_str(v)));
                }
            }
            if u.mirrors.is_empty() && child.is_empty() && u.flag_requests.is_empty() {
                return head;
            }
            let mut block = vec![format!("{head} {{")];
            for p in &child {
                let args: Vec<String> = p
                    .values
                    .iter()
                    .map(|v| {
                        if p.negated {
                            format!("(not)\"{}\"", kdl_str(v))
                        } else {
                            format!("\"{}\"", kdl_str(v))
                        }
                    })
                    .collect();
                block.push(format!("        {} {}", p.name, args.join(" ")));
            }
            for url in &u.mirrors {
                block.push(format!("        mirror (url)\"{}\"", kdl_str(url)));
            }
            for fr in &u.flag_requests {
                if fr.enabled {
                    block.push(format!("        flag \"{}\"", kdl_str(&fr.name)));
                } else {
                    block.push(format!("        flag \"{}\" #false", kdl_str(&fr.name)));
                }
            }
            block.push("    }".to_string());
            block.join("\n")
        }
        Dep::Member(m) => {
            // MemberDep predicates come exclusively from enclosing when blocks
            // (MAN-DEP-MEMBER-PROPS forbids inline properties).  Wrap if non-empty.
            if !m.predicates.is_empty() {
                let preds: Vec<&_> = m.predicates.iter().collect();
                let when_props = format_predicate_props(&preds);
                let inner = format!("        member \"{}\"", kdl_str(&m.name));
                format!("    when{when_props} {{\n{inner}\n    }}")
            } else {
                format!("    member \"{}\"", kdl_str(&m.name))
            }
        }
        Dep::Local(l) => {
            let mut node_body = format!("\"{}\" local=\"{}\"", kdl_str(&l.name), kdl_str(&l.path));
            if let Some(version) = &l.version {
                node_body.push_str(&format!(" version=\"{}\"", milpa_solver::format_version_str(version)));
            }
            if !l.predicates.is_empty() {
                let preds: Vec<&_> = l.predicates.iter().collect();
                let when_props = format_predicate_props(&preds);
                let inner = format!("        {node_body}");
                format!("    when{when_props} {{\n{inner}\n    }}")
            } else {
                format!("    {node_body}")
            }
        }
        Dep::Tarball(t) => {
            let mut parts = vec![
                format!("\"{}\"", kdl_str(&t.name)),
                format!("tarball=(url)\"{}\"", kdl_str(&t.url)),
            ];
            if let Some(sha) = &t.sha256 {
                parts.push(format!("sha256=\"{}\"", kdl_str(sha)));
            }
            if t.strip_components != 0 {
                parts.push(format!("strip_components={}", t.strip_components));
            }
            if let Some(version) = &t.version {
                parts.push(format!("version=\"{}\"", milpa_solver::format_version_str(version)));
            }
            if let Some(subpath) = &t.subpath {
                parts.push(format!("subpath=\"{}\"", kdl_str(subpath)));
            }
            let node_body = parts.join(" ");
            if !t.predicates.is_empty() {
                let preds: Vec<&_> = t.predicates.iter().collect();
                let when_props = format_predicate_props(&preds);
                let inner = format!("        {node_body}");
                format!("    when{when_props} {{\n{inner}\n    }}")
            } else {
                format!("    {node_body}")
            }
        }
        Dep::Named(n) => {
            // S7: strip the auto-injected gate predicate (flag=<depname>) — it's
            // implied by optional=#true and must not be double-emitted as a when-block
            // predicate.  All other predicates (from outer when blocks) ARE serialized.
            let when_preds: Vec<&_> = if n.optional {
                let auto_gate_val = n.name.as_str();
                n.predicates
                    .iter()
                    .filter(|p| {
                        !(p.name == "flag"
                            && p.values.len() == 1
                            && p.values[0] == auto_gate_val
                            && !p.negated)
                    })
                    .collect()
            } else {
                n.predicates.iter().collect()
            };

            // Build the dep node body (without leading indentation — added below).
            // S5b: emit `namespace="..."` attribute in canonical form (never slash).
            let ns_attr = match &n.namespace {
                Some(ns) => format!(" namespace=\"{}\"", kdl_str(ns)),
                None => String::new(),
            };
            // ns_attr is either "" or " namespace=\"ns\"" (with a leading space).
            // Result: `"name"`, `"name" "c"`, `"name" namespace="ns"`, or
            //         `"name" namespace="ns" "c"` — always single-spaced.
            let name_part = format!("\"{}\"{}",  kdl_str(&n.name), ns_attr);
            let mut head = match &n.constraint {
                None => name_part,
                Some(c) => format!("{} \"{}\"", name_part, kdl_str(c)),
            };
            // S7: emit `optional=#true`.
            if n.optional {
                head.push_str(" optional=#true");
            }

            if !n.flag_requests.is_empty() {
                // Multi-line block form for flag_requests (§3.1.5, S3 RFC #23).
                if !when_preds.is_empty() {
                    let when_props = format_predicate_props(&when_preds);
                    let mut inner_lines = vec![format!("        {head} {{")];
                    for fr in &n.flag_requests {
                        if fr.enabled {
                            inner_lines.push(format!("            flag \"{}\"", kdl_str(&fr.name)));
                        } else {
                            inner_lines.push(format!("            flag \"{}\" #false", kdl_str(&fr.name)));
                        }
                    }
                    inner_lines.push("        }".to_string());
                    let inner = inner_lines.join("\n");
                    format!("    when{when_props} {{\n{inner}\n    }}")
                } else {
                    let mut block = vec![format!("    {head} {{")];
                    for fr in &n.flag_requests {
                        if fr.enabled {
                            block.push(format!("        flag \"{}\"", kdl_str(&fr.name)));
                        } else {
                            block.push(format!("        flag \"{}\" #false", kdl_str(&fr.name)));
                        }
                    }
                    block.push("    }".to_string());
                    block.join("\n")
                }
            } else if !when_preds.is_empty() {
                let when_props = format_predicate_props(&when_preds);
                let inner = format!("        {head}");
                format!("    when{when_props} {{\n{inner}\n    }}")
            } else {
                format!("    {head}")
            }
        }
    }
}

