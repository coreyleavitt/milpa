    /// `kdl_str` helper must escape exactly as Python's `_kdl_str`.
    #[test]
    fn kdl_str_escapes_special_chars() {
        assert_eq!(kdl_str("hello"), "hello");
        assert_eq!(kdl_str(r#"say "hi""#), r#"say \"hi\""#);
        assert_eq!(kdl_str("back\\slash"), "back\\\\slash");
        assert_eq!(kdl_str("line\nfeed"), "line\\nfeed");
        assert_eq!(kdl_str("carriage\rreturn"), "carriage\\rreturn");
        assert_eq!(kdl_str("tab\there"), "tab\\there");
        // Backslash is escaped BEFORE quote (order matters for idempotency).
        assert_eq!(kdl_str("a\\\"b"), "a\\\\\\\"b");
    }

    /// A flag description containing `"` and `\` must serialize to valid escaped
    /// KDL and round-trip cleanly (parse(serialize(m)) == m).
