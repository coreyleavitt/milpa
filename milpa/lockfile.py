def verify_against_graph(
    lockfile: Lockfile,
    graph: ResolvedGraph,
) -> None:
    """Confirm the graph matches the lockfile dep-for-dep."""
    locked_by_name = {d.name: d for d in lockfile.deps}
    graph_by_name = {d.name: d for d in graph.deps}

    errors: list[str] = []
    for name in graph_by_name.keys() - locked_by_name.keys():
        errors.append(f"unexpected dep {name!r} in resolved graph (not in lockfile)")
    for name in locked_by_name.keys() - graph_by_name.keys():
        errors.append(f"locked dep {name!r} is missing from resolved graph")
    for name in graph_by_name.keys() & locked_by_name.keys():
        locked = locked_by_name[name]
        actual = graph_by_name[name]
        if locked.identity != actual.identity:
            errors.append(
                f"identity mismatch for {name!r}: "
                f"locked={locked.identity!r}, actual={actual.identity!r}"
            )

    if errors:
        raise LockfileError(
            "lockfile does not match resolved graph:\n  " + "\n  ".join(errors),
            code="LOCK-GRAPH-MISMATCH",
        )


def verify_lockfile_against_deps(
    lockfile: Lockfile,
    deps_dir: Path,
) -> list[str]:
    """Walk deps_dir/<name>/ for each locked dep and verify its
    identity matches the lockfile's recorded value."""
    divergences: list[str] = []
    locked_by_name = {d.name: d for d in lockfile.deps}

    for name, locked in locked_by_name.items():
        dep_path = deps_dir / name
        if not dep_path.exists():
            divergences.append(f"{name}: missing from {deps_dir}/")
            continue
        if not dep_path.is_dir():
            divergences.append(
                f"{name}: expected directory at {dep_path}, found something else"
            )
            continue
        actual = compute_content_hash(dep_path)
        expected = locked.identity
        if expected != actual:
            divergences.append(
                f"{name}: identity mismatch — "
                f"lockfile says {(expected or '<none>')[:23]}..., "
                f"actual {actual[:23]}..."
            )

    if deps_dir.exists() and deps_dir.is_dir():
        for entry in deps_dir.iterdir():
            if entry.name.startswith("."):
                continue
            if entry.name not in locked_by_name:
                divergences.append(
                    f"{entry.name}: extra dep in {deps_dir}/ not in lockfile"
                )

    return divergences


def verify_workspace_against_disk(
    workspace,  # Workspace from milpa.workspace
    lockfile: Lockfile,
) -> list[str]:
    """Workspace-aware drift detection.

    Each lockfile entry's first provenance determines its verification
    location: a MemberProvenanceRecord routes to the workspace member;
    everything else routes to <root>/_deps/<name>/.
    """
    members_by_name = {m.name: m for m in workspace.members}
    deps_dir = workspace.root / "_deps"
    divergences: list[str] = []

    for locked in lockfile.deps:
        member_target: Path | None = None
        if locked.provenances:
            first = locked.provenances[0]
            if isinstance(first, MemberProvenanceRecord):
                member = members_by_name.get(first.name)
                if member is None:
                    divergences.append(
                        f"{locked.name}: lockfile references workspace member "
                        f"{first.name!r} that is not in the current workspace"
                    )
                    continue
                member_target = member.directory

        target = member_target if member_target is not None else deps_dir / locked.name

        if not target.exists():
            divergences.append(f"{locked.name}: missing from {target}")
            continue
        if not target.is_dir():
            divergences.append(
                f"{locked.name}: expected directory at {target}, found something else"
            )
            continue
        actual = compute_content_hash(target)
        if locked.identity != actual:
            divergences.append(
                f"{locked.name}: identity mismatch — "
                f"lockfile says {(locked.identity or '<none>')[:23]}..., "
                f"actual {actual[:23]}..."
            )
    return divergences
