def parse_lockfile(text: str) -> Lockfile:
    """Parse KDL lockfile text into a Lockfile value."""
    try:
        doc = kdl.parse(text)
    except kdl.errors.ParseError as e:
        raise LockfileError(
            f"KDL syntax error: {e}", code="LOCK-KDL-SYNTAX"
        ) from e

    deps: list[LockedDep] = []
    strategy: str = "maxver"
    version: int | None = None
    for node in doc.nodes:
        if node.name == "version":
            version = _scalar_int(node, "version")
        elif node.name == "strategy":
            if len(node.args) == 1 and isinstance(node.args[0], str):
                strategy = node.args[0]
        elif node.name == "dep":
            deps.append(_parse_dep(node))

    if version is None:
        raise LockfileError(
            "lockfile missing required 'version' node",
            code="LOCK-VERSION-MISSING",
        )
    if version != LOCKFILE_SCHEMA_VERSION:
        raise LockfileError(
            f"unsupported lockfile schema version {version} "
            f"(this milpa understands version {LOCKFILE_SCHEMA_VERSION})",
            code="LOCK-VERSION-UNSUPPORTED",
        )

    return Lockfile(deps=tuple(deps), strategy=strategy, version=version)


def _scalar_int(node: kdl.Node, field_name: str) -> int:
    if len(node.args) != 1:
        raise LockfileError(
            f"{field_name!r} takes exactly one value",
            code="LOCK-FIELD-ARITY",
        )
    val = node.args[0]
    try:
        return int(val)  # type: ignore[arg-type]
    except (TypeError, ValueError) as e:
        raise LockfileError(
            f"{field_name!r} must be an integer (got {val!r})",
            code="LOCK-FIELD-TYPE",
        ) from e


def _parse_dep(node: kdl.Node) -> LockedDep:
    """Parse a dep block: identity + version + src_dir + requires +
    one-or-more provenance { ... } blocks."""
    name = _dep_name(node)
    identity = None
    version = "0.0.0"
    src_dir = ""
    requires: tuple[str, ...] = ()
    active_flags: tuple[str, ...] = ()
    self_mirrors: tuple[str, ...] = ()
    provenances: list[ProvenanceRecord] = []

    for child in node.nodes:
        if child.name == "identity":
            val = _scalar_str(child, name, "identity")
            try:
                identity = parse_identity(val)
            except IdentityError as e:
                raise LockfileError(
                    f"dep {name!r}: invalid identity — {e}",
                    code="LOCK-DEP-IDENTITY-INVALID",
                ) from e
        elif child.name == "version":
            version = _scalar_str(child, name, "version")
        elif child.name == "src_dir":
            src_dir = _scalar_str(child, name, "src_dir")
        elif child.name == "requires":
            requires = tuple(a for a in child.args if isinstance(a, str))
        elif child.name == "active_flags":
            active_flags = tuple(a for a in child.args if isinstance(a, str))
        elif child.name == "self_mirrors":
            # Accept both bare strings and (url)-annotated values (parsed
            # as ParseResult by kdl-py). url_value_to_str handles both and
            # returns "" for any other type — filter those out post-call so
            # no empty strings enter self_mirrors.
            from .kdl_util import url_value_to_str
            self_mirrors = tuple(
                s for a in child.args
                if (s := url_value_to_str(a))
            )
        elif child.name == "provenance":
            provenances.append(_parse_provenance_block(child, name))
        else:
            continue

    return LockedDep(
        name=name,
        identity=identity,
        version=version,
        src_dir=src_dir,
        requires=requires,
        provenances=tuple(provenances),
        active_flags=active_flags,
        self_mirrors=self_mirrors,
    )


def _parse_provenance_block(node: kdl.Node, dep_name: str) -> ProvenanceRecord:
    """Parse a `provenance { kind "..." ... }` block."""
    fields: dict[str, object] = {}
    for child in node.nodes:
        if len(child.args) != 1:
            raise LockfileError(
                f"dep {dep_name!r}: provenance field {child.name!r} "
                f"must have exactly one value",
                code="LOCK-PROV-FIELD-ARITY",
            )
        fields[child.name] = child.args[0]
    kind = fields.get("kind")
    if not isinstance(kind, str):
        raise LockfileError(
            f"dep {dep_name!r}: provenance block missing 'kind' discriminator",
            code="LOCK-PROV-KIND-MISSING",
        )
    if kind == "git":
        return GitProvenanceRecord(
            url=_required_str(fields, "url", dep_name),
            ref=_optional_str(fields, "ref"),
            commit_sha=_optional_str(fields, "commit_sha"),
        )
    if kind == "tarball":
        return TarballProvenanceRecord(
            url=_required_str(fields, "url", dep_name),
            sha256=_optional_str(fields, "sha256"),
        )
    if kind == "local":
        return LocalProvenanceRecord(
            path=_required_str(fields, "path", dep_name),
        )
    if kind == "member":
        return MemberProvenanceRecord(
            name=_required_str(fields, "name", dep_name),
        )
    if kind == "oci":
        return OciProvenanceRecord(
            registry=_required_str(fields, "registry", dep_name),
            repository=_required_str(fields, "repository", dep_name),
            digest=_required_str(fields, "digest", dep_name),
        )
    if kind == "registry":
        return RegistryProvenanceRecord(
            name=_required_str(fields, "name", dep_name),
            tag=_optional_str(fields, "tag"),
            commit_sha=_optional_str(fields, "commit_sha"),
        )
    raise LockfileError(
        f"dep {dep_name!r}: unknown provenance kind {kind!r} "
        f"(supported: git, tarball, local, member, oci, registry)",
        code="LOCK-PROV-KIND-UNKNOWN",
    )


def _dep_name(node: kdl.Node) -> str:
    if len(node.args) != 1 or not isinstance(node.args[0], str):
        raise LockfileError(
            "dep node requires exactly one string argument (the name)",
            code="LOCK-DEP-NAME-ARITY",
        )
    return node.args[0]


def _scalar_str(node: kdl.Node, dep_name: str, field_name: str) -> str:
    if len(node.args) != 1 or not isinstance(node.args[0], str):
        raise LockfileError(
            f"dep {dep_name!r} field {field_name!r} must have exactly one string value",
            code="LOCK-DEP-FIELD-ARITY",
        )
    return node.args[0]


def _required_str(fields: dict, key: str, dep_name: str) -> str:
    val = fields.get(key)
    if not isinstance(val, str):
        raise LockfileError(
            f"dep {dep_name!r}: provenance missing required field {key!r}",
            code="LOCK-PROV-FIELD-MISSING",
        )
    return val


def _optional_str(fields: dict, key: str) -> str | None:
    val = fields.get(key)
    if val is None:
        return None
    return val if isinstance(val, str) else None


