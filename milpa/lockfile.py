"""milpa.lock — reproducible-build snapshot of a resolved dep graph.

The lockfile records two distinct kinds of data per dep:

  - **Identity**: `identity` field (multihash-encoded sha256 of source
    tree per #34). The canonical 'what'. Trust-independent,
    recomputable from bytes alone. This is the field consumers verify
    against.
  - **Provenance**: one or more `ProvenanceRecord` entries. Each
    records "where these bytes came from" — URL, ref, commit sha,
    local path, workspace member name, etc. Trust-dependent; the git
    server / mirror / registry could disagree without notice. A
    single identity may have multiple provenances (Phase D #37 lights
    up multi-provenance application; #33 ships the schema with
    exactly one per dep).

See docs/identity-and-provenance.md for the model and
docs/rfc-content-addressed-identity.md §Proposed model for the
schema design.

Format is KDL. The `version` field is present from day one (a v1.0
lockfile starts at version 1) but pre-1.0 we evolve the schema by
editing v1 in place — no parallel codepaths, no migrations. Once
real consumers exist we will bump the version and grow proper
upgrade support.

Library vs application:
  The lockfile format is identical for both. Whether the lockfile is
  committed to version control depends on the manifest's `kind`:
    library     → don't commit (downstream consumers re-resolve)
    application → commit (deterministic builds)
  That decision belongs to the CLI / manifest layer, not here.
"""

from dataclasses import dataclass
from pathlib import Path

import kdl

from .error_codes import lockfile_codes as _LC  # noqa: F401 — populates catalog
from .fetchers.git import GitProvenance
from .fetchers.oci import OciProvenance
from .fetchers.tarball import TarballProvenance
from .identity import IdentityError, compute_content_hash, parse_identity
from .resolver import ResolvedDep, ResolvedGraph
from .solver import Version


LOCKFILE_SCHEMA_VERSION = 1
_HEADER = "// generated by milpa; reproducible build snapshot"


# ---------------------------------------------------------------------------
# ProvenanceRecord discriminated union (#33)
# ---------------------------------------------------------------------------
# Each variant captures the descriptive metadata for "where these
# bytes came from" per kind. Distinct from milpa.fetchers.types.Provenance
# which is "how to fetch from this source." The lockfile records
# provenance after the fact; the fetcher protocol uses Provenance
# before the fact.


@dataclass(frozen=True)
class GitProvenanceRecord:
    """Provenance for a git-fetched dep."""
    url: str
    ref: str | None
    commit_sha: str | None
    kind: str = "git"


@dataclass(frozen=True)
class TarballProvenanceRecord:
    """Provenance for a tarball-fetched dep."""
    url: str
    sha256: str | None       # archive sha256 (provenance receipt, NOT identity)
    kind: str = "tarball"


@dataclass(frozen=True)
class LocalProvenanceRecord:
    """Provenance for a local-path dep. `path` is the as-declared
    string (relative to project root)."""
    path: str
    kind: str = "local"


@dataclass(frozen=True)
class MemberProvenanceRecord:
    """Provenance for a workspace-internal member reference."""
    name: str
    kind: str = "member"


@dataclass(frozen=True)
class OciProvenanceRecord:
    """Provenance for an OCI-artifact-fetched dep (milpa#97). Mirrors
    fetchers.oci.OciProvenance; the digest is the immutable pin."""
    registry: str
    repository: str
    digest: str
    kind: str = "oci"


@dataclass(frozen=True)
class RegistryProvenanceRecord:
    """Provenance for a registry-resolved dep.

    READ-COMPAT ONLY (milpa#97): the writer never emits this again — named
    deps now write git/oci records. Kept so existing `milpa.lock`s with
    `kind "registry"` still parse; the dataclass is removed only once
    straggler old locks are regenerated (not on #97's critical path)."""
    name: str
    tag: str | None
    commit_sha: str | None
    kind: str = "registry"


ProvenanceRecord = (
    GitProvenanceRecord
    | TarballProvenanceRecord
    | LocalProvenanceRecord
    | MemberProvenanceRecord
    | OciProvenanceRecord
    | RegistryProvenanceRecord
)


# ---------------------------------------------------------------------------
# Lockfile data model
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class LockedDep:
    """A single dep entry in a lockfile.

    `identity` is the multihash-encoded content hash (#34). The
    `provenances` tuple records one or more ProvenanceRecord entries
    describing where the bytes came from. #33 ships with exactly one
    provenance per dep; #37 (Phase D) lights up multi-provenance.

    `active_flags` (#23) records the feature flag set active for this
    dep in the resolved graph. Empty tuple = no flags (or all defaults
    apply); omitted from emitted KDL when empty to keep diffs minimal.
    """
    name: str
    identity: str | None
    version: str
    src_dir: str
    requires: tuple[str, ...]
    provenances: tuple[ProvenanceRecord, ...]
    active_flags: tuple[str, ...] = ()
    # Self-mirrors harvested from this dep's milpa.kdl (#79).
    # Cached so subsequent resolves can fall through to them even
    # when the primary fetch fails before discovery.
    self_mirrors: tuple[str, ...] = ()


@dataclass(frozen=True)
class Lockfile:
    deps: tuple[LockedDep, ...]
    strategy: str = "maxver"
    version: int = LOCKFILE_SCHEMA_VERSION


class LockfileError(Exception):
    """Raised on malformed lockfile text or graph/lockfile mismatch.

    Carries a stable `code` (a `LOCK-*` slug from the error catalog) so
    callers can assert on condition rather than brittle message strings."""

    def __init__(self, message: str, *, code: str) -> None:
        self.code = code
        super().__init__(message)


# ---------------------------------------------------------------------------
# from_graph — bridge ResolvedDep (flat) → LockedDep (structured)
# ---------------------------------------------------------------------------


def from_graph(graph: ResolvedGraph, *, strategy: str = "maxver") -> Lockfile:
    """Convert a ResolvedGraph into a Lockfile.

    Deps are sorted by name for deterministic output — same graph
    always produces byte-identical lockfile text. `strategy` records
    which resolution strategy produced this lockfile (for diagnostics).
    """
    deps = tuple(sorted(
        (_locked_from_resolved(d) for d in graph.deps),
        key=lambda d: d.name,
    ))
    return Lockfile(deps=deps, strategy=strategy)


def _locked_from_resolved(d: ResolvedDep) -> LockedDep:
    """Translate a flat ResolvedDep into a structured LockedDep with
    the appropriate ProvenanceRecord variant based on the source
    field's prefix."""
    return LockedDep(
        name=d.name,
        identity=d.identity,
        version=_format_version(d.version),
        src_dir=d.src_dir,
        # Sort lexicographically: `requires` is accumulated in BFS
        # arrival order, which is not reproducible across parallel-fetch
        # runs or independent implementations. Lexicographic order is
        # the spec's single canonical ordering rule (lockfile-schema
        # §3.4 / resolver-semantics §4.4).
        requires=tuple(sorted(d.requires)),
        provenances=(_provenance_from_resolved(d),),
        active_flags=getattr(d, "active_flags", ()),
        self_mirrors=getattr(d, "self_mirrors", ()),
    )


def _provenance_from_resolved(d: ResolvedDep) -> ProvenanceRecord:
    """Reconstruct the lockfile ProvenanceRecord for a resolved dep.

    Primary path (#97 / Option A): dispatch on the type of the typed
    `provenance` object the resolver carried. This is the single source
    of truth — no source-string parsing, so the OCI case (whose flat
    `oci:{registry}/{repository}@{digest}` string is genuinely ambiguous
    to split) reconstructs cleanly by type.

    Fallback: when `provenance` is None (the synthetic root and workspace
    members — both never fetched, so they carry only a `source` marker),
    parse the `source` string. Named deps now always carry a typed git/oci
    provenance (milpa#97), so no `registry:` source string is ever
    produced; the bare-git arm remains a defensive catch-all."""
    # Dispatch lives here (the serialization layer) rather than as
    # Provenance.to_record() on the fetcher types: that would make
    # fetchers/* depend on lockfile record types — wrong layering
    # direction (fetchers are a lower layer than the lockfile).
    prov = d.provenance
    if isinstance(prov, GitProvenance):
        # commit_sha is the RESOLVED sha from the receipt (d.sha), not the
        # provenance's pin field — matches the legacy git arm exactly.
        return GitProvenanceRecord(url=prov.url, ref=prov.ref, commit_sha=d.sha)
    if isinstance(prov, TarballProvenance):
        # Preserve the declared expected_sha256 — this is the archive hash
        # recorded in the manifest (provenance receipt). Previously this was
        # incorrectly set to None, silently losing the declared hash (M11).
        return TarballProvenanceRecord(url=prov.url, sha256=prov.expected_sha256)
    if isinstance(prov, OciProvenance):
        return OciProvenanceRecord(
            registry=prov.registry,
            repository=prov.repository,
            digest=prov.digest,
        )
    # NOTE: LocalProvenance is intentionally absent here. _process_local in
    # resolver.py deliberately leaves provenance=None on local dep candidates
    # (see its comment: the typed LocalProvenance.path is absolute, but the
    # lockfile records the *declared relative* path). Local deps always reach
    # the source-string fallback below.
    if prov is not None:
        raise ValueError(
            f"dep {d.name!r}: unexpected typed provenance {type(prov).__name__!r} "
            f"— add a lockfile record arm for this provenance kind"
        )

    # --- None provenance: source-string fallback ---
    # Legitimate for: synthetic root, workspace members, local deps.
    src = d.source
    if src.startswith("local:"):
        return LocalProvenanceRecord(path=src[len("local:"):])
    if src.startswith("tarball:"):
        return TarballProvenanceRecord(url=src[len("tarball:"):], sha256=None)
    if src.startswith("member:"):
        return MemberProvenanceRecord(name=src[len("member:"):])
    return GitProvenanceRecord(url=src, ref=d.ref, commit_sha=d.sha)


def _format_version(v: Version) -> str:
    """Format a Version as a lossless semver string.

    Emits major.minor.patch[-pre][+build]. Build metadata is preserved
    for round-trip even though it is ignored for ordering and equality.
    Accepts both Version objects and bare 3-tuples (backward compat for
    tests and call sites that pass raw tuples).
    """
    if isinstance(v, Version):
        from .solver import _format_version_str
        return _format_version_str(v)
    # Bare tuple (e.g. (0, 0, 1)) — emit the release triple only.
    return f"{v[0]}.{v[1]}.{v[2]}"


